import { ProjectSettings } from '../types'
import { BEFORE_YOU_PICK, getHostingOption, HOSTING_CREDIT, HOSTING_OPTIONS, VPS_VS_CLOUD_VM_NOTE } from '../data/hosting'
import { hostingLabel, planHosting } from './hostingPlanner'

const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ')
const code = (value: string) => `\`${value}\``

/** `docs/hosting.md` for a generated project: where each app runs now, what the planner suggests, and why. */
export function renderHostingMarkdown(settings: ProjectSettings): string {
  const plan = planHosting(settings)
  const lines: string[] = [
    '# Hosting',
    '',
    'Generated by LazyStack from `lazystack.json`. Every app is **local only** until you choose a hosting type for it',
    '(in the Blueprint **Hosting** tab, with `lazystack hosting`, or by setting `hosting` on the app in `lazystack.json`).',
    'The suggestions are advice; nothing here changes the generated deploy files.',
    '',
    '## Apps',
    '',
    '| App | Hosting | Suggested | Why | Alternatives | Example services | Generated files to use |',
    '| --- | --- | --- | --- | --- | --- | --- |'
  ]
  for (const item of plan.apps) {
    const effective = item.effective ? getHostingOption(item.effective) : undefined
    const hosting = `${hostingLabel(item.effective)}${item.override ? '' : item.effective === 'local' ? ' (default)' : ''}`
    const alternatives = item.suggestion.alternatives.map(alt => `${hostingLabel(alt.type)}: ${alt.why}`).join('<br>') || '–'
    const examples = effective?.examples.join(', ') || '–'
    const files = item.files.map(file => file.path ? `${file.label} (${code(file.path)})` : file.label).join('<br>') || '–'
    lines.push(`| ${cell(item.app.folderName)} | ${cell(hosting)} | ${cell(hostingLabel(item.suggestion.type))} | ${cell(item.suggestion.reasons.join(' '))} | ${cell(alternatives)} | ${cell(examples)} | ${cell(files)} |`)
  }

  lines.push('', '## Stack notes', '', ...plan.notes.map(note => `- ${note}`))

  lines.push(
    '',
    '## Hosting types',
    '',
    '| Type | What it is | Good for | Watch out for | Examples | Upkeep |',
    '| --- | --- | --- | --- | --- | --- |',
    ...HOSTING_OPTIONS.map(option => `| ${option.label} | ${cell(option.summary)} | ${cell(option.goodFor.join('; '))} | ${cell(option.watchOutFor.join('; '))} | ${cell(option.examples.join(', '))} | ${option.upkeep} |`),
    '',
    `**VPS vs cloud VM.** ${VPS_VS_CLOUD_VM_NOTE}`,
    '',
    '## Before you pick',
    '',
    ...BEFORE_YOU_PICK.map(item => `- ${item}`),
    '',
    `${HOSTING_CREDIT.text}: ${HOSTING_CREDIT.url}`,
    ''
  )
  return lines.join('\n')
}
