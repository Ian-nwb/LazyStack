import { CartApp, SelectedDatabase } from '../types'
import { DATABASE_CATALOG } from './databases'

/**
 * First-run steps that LazyStack cannot do for you (beyond "Install Packages" and having the
 * framework's toolchain on PATH): generating platform folders, signing in to a hosted service,
 * installing system libraries or CLIs, creating secrets, and so on.
 */
export interface ManualSetup {
  /** One line on why this is needed. */
  reason: string
  /** Ordered steps; text inside backticks is shown as a command. */
  steps: string[]
  docs?: string
}

const snakeName = (folderName: string) => folderName.split(/[^a-zA-Z0-9]+/).filter(Boolean).join('_').toLowerCase() || 'app'

const LINUX_GUI_LIBS = 'Debian/Ubuntu: `sudo apt install pkg-config libxkbcommon-dev libwayland-dev libx11-dev libfontconfig1-dev`; Fedora: `sudo dnf install libxkbcommon-devel wayland-devel libX11-devel fontconfig-devel`'

export function getAppManualSetup(app: Pick<CartApp, 'techId' | 'folderName' | 'port' | 'starterProfile'>): ManualSetup | null {
  const snake = snakeName(app.folderName)
  switch (app.techId) {
    case 'dart-flutter':
      return {
        reason: 'Platform runner folders (android/, ios/, web/, linux/, macos/, windows/) are generated by your installed Flutter SDK so they match its version.',
        steps: [`In the app folder run \`flutter create --project-name ${snake} .\``, 'Run `flutter pub get`, then `flutter run` (add `-d chrome` or a device id to pick a target).'],
        docs: 'https://docs.flutter.dev/get-started/install'
      }
    case 'react-native-expo':
      return {
        reason: 'Expo apps run on a phone or an emulator, not in Docker.',
        steps: ['Install Expo Go on your phone, or set up an Android emulator (Android Studio) / iOS Simulator (Xcode on macOS).', 'Run `npx expo start` and scan the QR code or press `a` / `i`.', 'On a physical phone, replace `localhost` in `.env` (`EXPO_PUBLIC_API_URL`) with your computer\'s LAN IP.'],
        docs: 'https://docs.expo.dev/get-started/set-up-your-environment/'
      }
    case 'ionic-framework':
    case 'capacitor-app':
      return {
        reason: 'The web build works out of the box; native Android/iOS shells are added with Capacitor and need the platform SDKs.',
        steps: ['For native builds install Android Studio (Android) or Xcode on macOS (iOS).', 'Run `npm install @capacitor/android` (or `@capacitor/ios`), `npm run build`, then `npx cap add android` (or `ios`) and `npx cap sync`.'],
        docs: 'https://capacitorjs.com/docs/getting-started/environment-setup'
      }
    case 'csharp-maui':
      return {
        reason: '.NET MAUI needs the MAUI workload and the platform SDKs. Linux hosts can build the Android target only; iOS and Mac Catalyst need macOS with Xcode.',
        steps: [
          'Install the .NET 10 SDK, then `dotnet workload install maui` (on Linux: `dotnet workload install maui-android`).',
          'For Android install Android Studio (SDK + emulator), or run `dotnet build -t:InstallAndroidDependencies -f net10.0-android -p:AcceptAndroidSDKLicenses=True`.',
          'Run `dotnet build -t:Run -f net10.0-android` (or `net10.0-maccatalyst` on macOS, `net10.0-windows10.0.19041.0` on Windows).',
          'Copy your backend URL from `.env` into `Services/ApiConfig.cs`; MAUI apps do not read `.env` at runtime.'
        ],
        docs: 'https://learn.microsoft.com/dotnet/maui/get-started/installation'
      }
    case 'tauri-app':
      return {
        reason: 'Tauri compiles a Rust desktop shell that links against your OS webview.',
        steps: ['Install Rust (https://rustup.rs) and the Tauri system dependencies. Debian/Ubuntu: `sudo apt install libwebkit2gtk-4.1-dev libgtk-3-dev librsvg2-dev libssl-dev build-essential`. Windows needs the WebView2 runtime and MSVC build tools.', 'Run `npm install`, then `npm run dev`.'],
        docs: 'https://tauri.app/start/prerequisites/'
      }
    case 'google-apps-script':
      return {
        reason: 'Apps Script projects live in your Google account and are deployed with clasp.',
        steps: ['Enable the Apps Script API at https://script.google.com/home/usersettings.', 'Run `npx clasp login`.', 'Run `npx clasp create --type standalone --rootDir dist` or put an existing script id in `.clasp.json` (it ships as `YOUR_SCRIPT_ID_HERE`).', 'Run `npm run build`, then `npx clasp push`.'],
        docs: 'https://developers.google.com/apps-script/guides/clasp'
      }
    case 'python-anvil':
      return {
        reason: 'Anvil apps are hosted on anvil.works; this folder only holds the plan and uplink code.',
        steps: ['Create the app at https://anvil.works/build.', 'Enable the Server Uplink in the app and copy its key into this app\'s `.env`.'],
        docs: 'https://anvil.works/docs/uplink'
      }
    case 'swiftui-client':
      return {
        reason: 'SwiftUI apps build only with Xcode on macOS.',
        steps: ['Open `Package.swift` in Xcode on a Mac and run the target.'],
        docs: 'https://developer.apple.com/xcode/'
      }
    case 'rust-dioxus':
      return {
        reason: 'Dioxus apps are served and bundled by the `dx` CLI.',
        steps: ['Run `cargo install dioxus-cli` and `rustup target add wasm32-unknown-unknown`.', `Run \`dx serve --port ${app.port || 8080}\` (or \`dx serve --platform desktop\`). Desktop on Linux also needs \`libwebkit2gtk-4.1-dev\` and \`libxdo-dev\`.`],
        docs: 'https://dioxuslabs.com/learn/0.7/getting_started/'
      }
    case 'rust-yew':
    case 'rust-leptos':
      return {
        reason: 'WebAssembly frontends are built with Trunk for the wasm32 target.',
        steps: ['Run `rustup target add wasm32-unknown-unknown`.', 'Run `cargo install --locked trunk`, then `trunk serve`.'],
        docs: 'https://trunkrs.dev/'
      }
    case 'rust-bevy':
      return {
        reason: 'Bevy links against audio, input and windowing system libraries on Linux.',
        steps: ['Debian/Ubuntu: `sudo apt install pkg-config libasound2-dev libudev-dev libwayland-dev libxkbcommon-dev`; Fedora: `sudo dnf install alsa-lib-devel systemd-devel wayland-devel libxkbcommon-devel`. Windows and macOS need nothing extra.', 'Run `cargo run` (the first build takes several minutes).'],
        docs: 'https://bevy.org/learn/quick-start/getting-started/setup/'
      }
    case 'rust-slint':
      return {
        reason: 'Slint renders through your OS windowing and font libraries on Linux.',
        steps: [LINUX_GUI_LIBS + '. Windows and macOS need nothing extra.', 'Run `cargo run`.'],
        docs: 'https://docs.slint.dev/latest/docs/slint/guide/platforms/desktop/'
      }
    case 'rust-gpui':
      return {
        reason: 'GPUI draws with the GPU (Vulkan on Linux, Metal on macOS).',
        steps: [LINUX_GUI_LIBS + ', plus Vulkan drivers (`mesa-vulkan-drivers` / your GPU vendor\'s driver).', 'Run `cargo run`.'],
        docs: 'https://github.com/zed-industries/zed/tree/main/crates/gpui'
      }
    case 'ocaml-dream':
      return {
        reason: 'OCaml packages come from opam, and Dream needs C libraries.',
        steps: ['Install opam (https://opam.ocaml.org/doc/Install.html) and run `opam init`.', 'Install `pkg-config`, `libev` and OpenSSL headers (Debian/Ubuntu: `sudo apt install pkg-config libev-dev libssl-dev`).', 'Run `opam install . --deps-only`, then `dune exec ./bin/server.exe`.'],
        docs: 'https://aantron.github.io/dream/'
      }
    case 'cpp-drogon':
      return {
        reason: 'Drogon is a C++ library that must be installed system-wide before CMake can find it.',
        steps: ['Build and install Drogon (https://github.com/drogonframework/drogon/wiki/ENG-02-Installation) or use the Docker service.', 'Run `cmake -B build && cmake --build build`, then `./build/drogon_service`.'],
        docs: 'https://github.com/drogonframework/drogon'
      }
    case 'c-microhttpd':
      return {
        reason: 'The service links against GNU libmicrohttpd.',
        steps: ['Install the library: Debian/Ubuntu `sudo apt install libmicrohttpd-dev`; Fedora `sudo dnf install libmicrohttpd-devel`; macOS `brew install libmicrohttpd`.', 'Run `make run`.']
      }
    case 'assembly-nasm':
      return {
        reason: 'The NASM starter uses raw Linux x86_64 system calls.',
        steps: ['Use Linux on x86_64 (or the Docker service) and install `nasm` and `binutils`.', 'Run `make run`.']
      }
    case 'haskell-scotty':
      return {
        reason: 'Cabal needs a package index before the first build.',
        steps: ['Install GHC and cabal with GHCup (https://www.haskell.org/ghcup/).', 'Run `cabal update`, then `cabal run`.']
      }
    case 'nim-happyx':
      return { reason: 'HappyX is installed with Nimble.', steps: ['Run `nimble install happyx`.', 'Run `nim c -r main.nim`.'] }
    case 'r-plumber':
      return { reason: 'R packages are installed from inside R.', steps: ['Run `Rscript -e "install.packages(\'plumber\', repos=\'https://cloud.r-project.org\')"`.', `Run \`Rscript -e "plumber::plumb('plumber.R')$run(host='0.0.0.0', port=${app.port || 8000})"\`.`] }
    case 'lua-lapis':
      return {
        reason: 'Lapis runs inside OpenResty and is installed with LuaRocks.',
        steps: ['Install OpenResty (https://openresty.org/en/download.html) and LuaRocks.', 'Run `luarocks install lapis`, then `lapis server`.']
      }
    case 'fullstack-laravel':
      return {
        reason: 'Laravel refuses to boot without an application key.',
        steps: ['Run `composer install` (or Install Packages).', 'Run `php artisan key:generate`, then `php artisan migrate`.']
      }
    case 'php-symfony':
      return {
        reason: 'The generated APP_SECRET is a placeholder.',
        steps: ['Replace `APP_SECRET` in the app\'s `.env` with a random value, e.g. `php -r "echo bin2hex(random_bytes(16));"`.']
      }
    case 'python-fastapi':
      return app.starterProfile === 'api-service'
        ? { reason: 'The API service profile uses a database schema and a bearer token.', steps: ['Set `API_TOKEN` in the app\'s `.env`.', 'Run `alembic upgrade head` inside the virtualenv before starting the API.'] }
        : null
    case 'sql-migrations':
      return {
        reason: 'Migrations run against a database you point them at.',
        steps: ['Install the `psql` or `mysql` client and set `DATABASE_URL` in the app\'s `.env`.', 'Apply the files in `migrations/` in order.']
      }
    default:
      return null
  }
}

/** Managed cloud databases need credentials from the provider's dashboard. */
export function getDatabaseManualSetup(db: SelectedDatabase): ManualSetup | null {
  const def = DATABASE_CATALOG.find(item => item.id === db.type)
  if (!def?.isCloud) return null
  return {
    reason: `${def.name} is a hosted service, so LazyStack cannot create its credentials.`,
    steps: [
      `Create a project in the ${def.name} dashboard${def.docsUrl ? ` (${def.docsUrl})` : ''}.`,
      `Copy its values into the project \`.env\`${def.envVars?.length ? `: ${def.envVars.map(name => `\`${name}\``).join(', ')}` : ''}.`
    ],
    docs: def.docsUrl
  }
}
