/**
 * Renders the full catalog (frameworks, databases and services, admin UIs, testing tools,
 * architecture layouts, stack presets, proxies) into README.md between the catalog markers.
 *
 *   npm run docs:catalog            rewrite README.md
 *   npm run docs:catalog -- --check exit 1 if README.md is out of date (CI)
 */
import fs from 'fs'
import path from 'path'
import { TECH_CATALOG } from '../src/data/frameworks'
import { DATABASE_CATALOG } from '../src/data/databases'
import { getDatabaseAdminUiOptions } from '../src/data/databaseAdminUis'
import { TESTING_TOOLS, TESTING_CATEGORIES } from '../src/data/testingTools'
import { ARCHITECTURE_PRESETS } from '../src/data/structurePresets'
import { STACK_PRESETS } from '../src/data/presets'
import type { AppRole, DatabaseOption } from '../src/types'

const README = path.resolve(process.cwd(), 'README.md')
const START = '<!-- catalog:start (generated by `npm run docs:catalog`; do not edit by hand) -->'
const END = '<!-- catalog:end -->'

const ROLE_LABEL: Record<AppRole, string> = {
  frontend: 'frontend',
  backend: 'backend',
  fullstack: 'full-stack',
  worker: 'worker',
  'desktop-mobile': 'desktop/mobile',
  'static-site': 'static site',
  other: 'script/other'
}

const DB_CATEGORY_LABEL: Record<DatabaseOption['category'], string> = {
  relational: 'Relational (SQL)',
  document: 'Document',
  'key-value': 'Key-value',
  cache: 'Cache',
  olap: 'Analytics (OLAP) and time series',
  graph: 'Graph',
  embedded: 'Embedded',
  vector: 'Vector',
  search: 'Search',
  storage: 'Object storage',
  'message-broker': 'Message brokers and streaming',
  baas: 'Backend as a service (SDK client + env vars)',
  'cloud-db': 'Managed cloud databases (SDK client + env vars)'
}

/** The catalog's language field is a display label; fold runtime-specific labels into one language row. */
const LANGUAGE_FAMILY: Record<string, string> = {
  'JS / TS': 'JavaScript / TypeScript',
  TypeScript: 'JavaScript / TypeScript',
  'Node.js': 'JavaScript / TypeScript',
  'JavaScript / TypeScript': 'JavaScript / TypeScript',
  'Bun (TS/JS)': 'JavaScript / TypeScript',
  'Deno (TS/JS)': 'JavaScript / TypeScript',
  'AssemblyScript / TypeScript': 'JavaScript / TypeScript',
  'Rust / WebAssembly': 'Rust',
  'Rust / Web': 'Rust',
  'HTML/CSS': 'HTML / CSS / JS',
  'HTML/CSS/JS': 'HTML / CSS / JS'
}
const languageOf = (language: string) => LANGUAGE_FAMILY[language] ?? language

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()

function groupBy<T>(items: T[], key: (item: T) => string): Map<string, T[]> {
  const map = new Map<string, T[]>()
  for (const item of items) {
    const k = key(item)
    if (!map.has(k)) map.set(k, [])
    map.get(k)!.push(item)
  }
  return map
}

function render(): string {
  const out: string[] = []
  const sortedLanguages = [...groupBy(TECH_CATALOG, t => languageOf(t.language)).entries()].sort(
    (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0])
  )

  out.push('## Supported frameworks, databases and tools')
  out.push('')
  out.push(
    `LazyStack ships **${TECH_CATALOG.length} frameworks** in ${sortedLanguages.length} languages, ` +
      `**${DATABASE_CATALOG.length} databases and services**, ${TESTING_TOOLS.length} testing tools, ` +
      `${ARCHITECTURE_PRESETS.length} architecture layouts, ${STACK_PRESETS.length} stack presets and 4 reverse proxies. ` +
      'Every framework below generates a framework-native starter with a Dockerfile, a test, a README and a `.gitignore`.'
  )
  out.push('')

  out.push(`### Frameworks (${TECH_CATALOG.length})`)
  out.push('')
  out.push('| Language | Frameworks and app types |')
  out.push('| --- | --- |')
  for (const [language, techs] of sortedLanguages) {
    const names = techs.map(t => `${t.name} (${ROLE_LABEL[t.role]}${t.experimental ? ', experimental' : ''})`)
    out.push(`| ${cell(language)} | ${cell(names.join(', '))} |`)
  }
  out.push('')

  out.push(`### Databases, brokers and cloud services (${DATABASE_CATALOG.length})`)
  out.push('')
  out.push('Self-hosted ones run in Docker Compose with a healthcheck and generated credentials; cloud ones get an SDK client file and environment variables.')
  out.push('')
  out.push('| Category | Services |')
  out.push('| --- | --- |')
  const dbOrder = Object.keys(DB_CATEGORY_LABEL) as DatabaseOption['category'][]
  const dbGroups = groupBy(DATABASE_CATALOG, d => d.category)
  for (const category of dbOrder) {
    const dbs = dbGroups.get(category)
    if (!dbs?.length) continue
    out.push(`| ${DB_CATEGORY_LABEL[category]} | ${cell(dbs.map(d => d.name).join(', '))} |`)
  }
  out.push('')

  const adminRows = DATABASE_CATALOG.map(d => ({ db: d.name, uis: getDatabaseAdminUiOptions(d.id) })).filter(r => r.uis.length)
  out.push('### Database admin UIs')
  out.push('')
  out.push('| Database | Admin UIs |')
  out.push('| --- | --- |')
  for (const row of adminRows) out.push(`| ${cell(row.db)} | ${cell(row.uis.map(u => u.name).join(', '))} |`)
  out.push('')

  out.push(`### Testing tools (${TESTING_TOOLS.length})`)
  out.push('')
  out.push('| Category | Tools |')
  out.push('| --- | --- |')
  const toolGroups = groupBy(TESTING_TOOLS, t => t.category)
  for (const category of TESTING_CATEGORIES) {
    const tools = toolGroups.get(category.id)
    if (!tools?.length) continue
    out.push(`| ${category.label} | ${cell(tools.map(t => t.name).join(', '))} |`)
  }
  out.push('')

  out.push(`### Architecture layouts (${ARCHITECTURE_PRESETS.length})`)
  out.push('')
  out.push('| Layout | Structure |')
  out.push('| --- | --- |')
  for (const preset of ARCHITECTURE_PRESETS) out.push(`| ${cell(preset.name)} | ${cell(preset.tagline)} |`)
  out.push('')

  out.push(`### Stack presets (${STACK_PRESETS.length})`)
  out.push('')
  out.push('One-click starting points, also available as `lazystack scaffold --preset <id>`.')
  out.push('')
  out.push('| Preset | id | What you get |')
  out.push('| --- | --- | --- |')
  for (const preset of STACK_PRESETS) out.push(`| ${cell(preset.name)} | \`${preset.id}\` | ${cell(preset.tagline)} |`)
  out.push('')

  out.push('### Reverse proxies and deployment')
  out.push('')
  out.push('- **Reverse proxies:** Nginx, Apache httpd, Caddy, Traefik (or none).')
  out.push('- **Deployment files:** Docker Compose (production and dev), Kubernetes manifests, a Helm chart, Terraform for AWS, GCP and DigitalOcean, and GitHub Actions workflows.')
  out.push('- **Workspace modes:** native-only (each app keeps only its own ecosystem files) or a unified pnpm + Turborepo workspace with shared `packages/types`.')

  return out.join('\n')
}

const readme = fs.readFileSync(README, 'utf8')
const startIdx = readme.indexOf(START)
const endIdx = readme.indexOf(END)
if (startIdx < 0 || endIdx < startIdx) {
  console.error(`README.md is missing the catalog markers:\n${START}\n${END}`)
  process.exit(1)
}
const next = `${readme.slice(0, startIdx + START.length)}\n\n${render()}\n\n${readme.slice(endIdx)}`

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md catalog is out of date. Run `npm run docs:catalog` and commit the result.')
    process.exit(1)
  }
  console.log('README.md catalog is up to date.')
} else {
  fs.writeFileSync(README, next)
  console.log(`README.md catalog updated (${TECH_CATALOG.length} frameworks, ${DATABASE_CATALOG.length} databases and services).`)
}
