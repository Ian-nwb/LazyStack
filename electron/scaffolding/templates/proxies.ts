import { ProjectSettings } from '../../../src/types'

export function generateNginxConfig(settings: ProjectSettings): { 'nginx.conf': string, 'default.conf': string } {
  let defaultConf = `# Generated by LazyStack for ${settings.projectName}\n\n`

  // Upstream definitions
  settings.apps.forEach(app => {
    const upstreamName = `upstream_${app.folderName.replace(/-/g, '_')}`
    const targetHost = app.runMode === 'docker' ? app.folderName : 'host.docker.internal'
    defaultConf += `upstream ${upstreamName} {\n  server ${targetHost}:${app.port};\n}\n\n`
  })

  defaultConf += `server {\n`
  defaultConf += `  listen ${settings.proxy.httpPort};\n`
  defaultConf += `  server_name localhost;\n\n`

  // Routes
  settings.apps.forEach(app => {
    const upstreamName = `upstream_${app.folderName.replace(/-/g, '_')}`
    const locationPath = app.routePrefix || `/${app.folderName}`

    defaultConf += `  # Routing for ${app.folderName} (${app.techId})\n`
    defaultConf += `  location ${locationPath} {\n`
    defaultConf += `    proxy_pass http://${upstreamName};\n`
    defaultConf += `    proxy_http_version 1.1;\n`
    defaultConf += `    proxy_set_header Upgrade $http_upgrade;\n`
    defaultConf += `    proxy_set_header Connection "upgrade";\n`
    defaultConf += `    proxy_set_header Host $host;\n`
    defaultConf += `    proxy_set_header X-Real-IP $remote_addr;\n`
    defaultConf += `    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n`
    defaultConf += `    proxy_set_header X-Forwarded-Proto $scheme;\n`
    defaultConf += `  }\n\n`
  })

  defaultConf += `}\n`

  const nginxConf = `user  nginx;
worker_processes  auto;
error_log  /var/log/nginx/error.log notice;
pid        /var/run/nginx.pid;

events {
    worker_connections  1024;
}

http {
    include       /etc/nginx/mime.types;
    default_type  application/octet-stream;
    log_format  main  '$remote_addr - $remote_user [$time_local] "$request" '
                      '$status $body_bytes_sent "$http_referer" '
                      '"$http_user_agent" "$http_x_forwarded_for"';
    access_log  /var/log/nginx/access.log  main;
    sendfile        on;
    keepalive_timeout  65;
    include /etc/nginx/conf.d/*.conf;
}
`

  return { 'nginx.conf': nginxConf, 'default.conf': defaultConf }
}

export function generateApacheConfig(settings: ProjectSettings): string {
  let conf = `# Generated by LazyStack for ${settings.projectName}\n`
  conf += `ServerRoot "/usr/local/apache2"\nListen ${settings.proxy.httpPort}\n\n`
  conf += `LoadModule mpm_event_module modules/mod_mpm_event.so\n`
  conf += `LoadModule authn_file_module modules/mod_authn_file.so\n`
  conf += `LoadModule authn_core_module modules/mod_authn_core.so\n`
  conf += `LoadModule authz_host_module modules/mod_authz_host.so\n`
  conf += `LoadModule authz_core_module modules/mod_authz_core.so\n`
  conf += `LoadModule proxy_module modules/mod_proxy.so\n`
  conf += `LoadModule proxy_http_module modules/mod_proxy_http.so\n`
  conf += `LoadModule proxy_wstunnel_module modules/mod_proxy_wstunnel.so\n`
  conf += `LoadModule dir_module modules/mod_dir.so\n\n`

  conf += `<VirtualHost *:${settings.proxy.httpPort}>\n`
  conf += `  ServerName localhost\n`
  conf += `  ProxyPreserveHost On\n\n`

  settings.apps.forEach(app => {
    const targetHost = app.runMode === 'docker' ? app.folderName : 'host.docker.internal'
    const route = app.routePrefix || `/${app.folderName}`
    conf += `  ProxyPass ${route} http://${targetHost}:${app.port}/\n`
    conf += `  ProxyPassReverse ${route} http://${targetHost}:${app.port}/\n\n`
  })

  conf += `</VirtualHost>\n`
  return conf
}
