import { ProjectSettings } from '../../../src/types'
import { getRoutePrefix } from '../../../src/utils/serviceConnections'

const routeOf = getRoutePrefix

export function generateNginxConfig(settings: ProjectSettings): { 'nginx.conf': string, 'default.conf': string } {
  let defaultConf = `# Generated by LazyStack for ${settings.projectName}\n\n`

  // Upstream definitions
  settings.apps.forEach(app => {
    const upstreamName = `upstream_${app.folderName.replace(/-/g, '_')}`
    const targetHost = app.runMode === 'docker' ? app.folderName : 'host.docker.internal'
    defaultConf += `upstream ${upstreamName} {\n  server ${targetHost}:${app.port};\n}\n\n`
  })

  defaultConf += `server {\n`
  defaultConf += `  listen ${settings.proxy.httpPort};\n`
  defaultConf += `  server_name localhost;\n\n`

  // Routes
  settings.apps.forEach(app => {
    const upstreamName = `upstream_${app.folderName.replace(/-/g, '_')}`
    const route = routeOf(app)

    defaultConf += `  # Routing for ${app.folderName} (${app.techId})\n`
    // A trailing slash on both sides makes nginx replace the prefix: /api/health -> /health.
    if (route !== '/') defaultConf += `  location = ${route} {\n    return 308 ${route}/$is_args$args;\n  }\n`
    defaultConf += `  location ${route === '/' ? '/' : `${route}/`} {\n`
    defaultConf += `    proxy_pass http://${upstreamName}${route === '/' ? '' : '/'};\n`
    defaultConf += `    proxy_http_version 1.1;\n`
    defaultConf += `    proxy_set_header Upgrade $http_upgrade;\n`
    defaultConf += `    proxy_set_header Connection "upgrade";\n`
    defaultConf += `    proxy_set_header Host $host;\n`
    defaultConf += `    proxy_set_header X-Real-IP $remote_addr;\n`
    defaultConf += `    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n`
    defaultConf += `    proxy_set_header X-Forwarded-Proto $scheme;\n`
    defaultConf += `  }\n\n`
  })

  defaultConf += `}\n`

  const nginxConf = `user  nginx;
worker_processes  auto;
error_log  /var/log/nginx/error.log notice;
pid        /var/run/nginx.pid;

events {
    worker_connections  1024;
}

http {
    include       /etc/nginx/mime.types;
    default_type  application/octet-stream;
    log_format  main  '$remote_addr - $remote_user [$time_local] "$request" '
                      '$status $body_bytes_sent "$http_referer" '
                      '"$http_user_agent" "$http_x_forwarded_for"';
    access_log  /var/log/nginx/access.log  main;
    sendfile        on;
    keepalive_timeout  65;
    include /etc/nginx/conf.d/*.conf;
}
`

  return { 'nginx.conf': nginxConf, 'default.conf': defaultConf }
}

export function generateApacheConfig(settings: ProjectSettings): string {
  let conf = `# Generated by LazyStack for ${settings.projectName}\n`
  conf += `ServerRoot "/usr/local/apache2"\nListen ${settings.proxy.httpPort}\nServerName localhost\nErrorLog /proc/self/fd/2\n\n`
  conf += `LoadModule mpm_event_module modules/mod_mpm_event.so\n`
  // httpd refuses to serve as root without mod_unixd dropping privileges.
  conf += `LoadModule unixd_module modules/mod_unixd.so\n`
  conf += `LoadModule authn_file_module modules/mod_authn_file.so\n`
  conf += `LoadModule authn_core_module modules/mod_authn_core.so\n`
  conf += `LoadModule authz_host_module modules/mod_authz_host.so\n`
  conf += `LoadModule authz_core_module modules/mod_authz_core.so\n`
  conf += `LoadModule proxy_module modules/mod_proxy.so\n`
  conf += `LoadModule proxy_http_module modules/mod_proxy_http.so\n`
  conf += `LoadModule proxy_wstunnel_module modules/mod_proxy_wstunnel.so\n`
  conf += `LoadModule dir_module modules/mod_dir.so\n\n`
  conf += `User daemon\nGroup daemon\n\n`

  conf += `<VirtualHost *:${settings.proxy.httpPort}>\n`
  conf += `  ServerName localhost\n`
  conf += `  ProxyPreserveHost On\n\n`

  // Apache uses the first matching ProxyPass, so longer prefixes must come before '/'.
  const ordered = [...settings.apps].sort((a, b) => routeOf(b).length - routeOf(a).length)
  ordered.forEach(app => {
    const targetHost = app.runMode === 'docker' ? app.folderName : 'host.docker.internal'
    const route = routeOf(app)
    const from = route === '/' ? '/' : `${route}/`
    conf += `  ProxyPass ${from} http://${targetHost}:${app.port}/\n`
    conf += `  ProxyPassReverse ${from} http://${targetHost}:${app.port}/\n\n`
  })

  conf += `</VirtualHost>\n`
  return conf
}

export function generateCaddyConfig(settings: ProjectSettings): string {
  let config = `# Generated by LazyStack for ${settings.projectName}\n:${settings.proxy.httpPort} {\n`
  settings.apps.forEach(app => {
    const route = routeOf(app)
    const host = app.runMode === 'docker' ? app.folderName : 'host.docker.internal'
    // handle_path strips the matched prefix before proxying.
    config += route === '/'
      ? `  handle {\n    reverse_proxy ${host}:${app.port}\n  }\n`
      : `  handle_path ${route}/* {\n    reverse_proxy ${host}:${app.port}\n  }\n`
  })
  config += `  respond / "LazyStack gateway is online" 200\n}\n`
  return config
}

/** Indents YAML blocks four spaces so they nest under `http.<section>:`. */
const indent = (blocks: string[]) => blocks.join('\n').split('\n').map(line => `    ${line}`).join('\n')

export function generateTraefikConfig(settings: ProjectSettings): { 'traefik.yml': string; 'dynamic.yml': string } {
  const config = `# Generated by LazyStack for ${settings.projectName}\nentryPoints:\n  web:\n    address: ":${settings.proxy.httpPort}"\nproviders:\n  file:\n    filename: /etc/traefik/dynamic.yml\n    watch: true\n`
  const routers: string[] = []
  const services: string[] = []
  const middlewares: string[] = []
  settings.apps.forEach((app, index) => {
    const name = app.folderName.toLowerCase().replace(/[^a-z0-9-]/g, '-') || `service-${index + 1}`
    const route = routeOf(app)
    const host = app.runMode === 'docker' ? app.folderName : 'host.docker.internal'
    const rule = route === '/' ? 'PathPrefix(`/`)' : `PathPrefix(\`${route}\`)`
    const strip = route === '/' ? '' : `\n  middlewares:\n    - ${name}-strip`
    if (route !== '/') middlewares.push(`${name}-strip:\n  stripPrefix:\n    prefixes:\n      - "${route}"`)
    routers.push(`${name}:\n  rule: "${rule}"\n  service: ${name}${strip}\n  entryPoints:\n    - web`)
    services.push(`${name}:\n  loadBalancer:\n    servers:\n      - url: "http://${host}:${app.port}"`)
  })
  return {
    'traefik.yml': config,
    'dynamic.yml': `# Generated file provider routes\nhttp:\n  routers:\n${indent(routers)}\n${middlewares.length ? `  middlewares:\n${indent(middlewares)}\n` : ''}  services:\n${indent(services)}\n`
  }
}
