/** Pre-commit checks using each toolchain's built-in formatter, scoped to the app folders that use it. */
export function generateLefthook(settings: ProjectSettings): string {
  const paths = resolveStructurePaths(settings)
  const commands: string[] = []
  for (const app of settings.apps) {
    const root = paths.getAppRelativePath(app.folderName, app.id, app.role) + '/'
    const id = app.techId
    const add = (name: string, glob: string, run: string) => commands.push(`    ${app.folderName}-${name}:\n      root: "${root}"\n      glob: "${glob}"\n      run: ${run}`)
    if (id.startsWith('go-') || id === 'vanilla-go') add('gofmt', '*.go', 'test -z "$(gofmt -l {staged_files})"')
    else if (id.startsWith('rust-') || id === 'tauri-app') add('rustfmt', '*.rs', 'cargo fmt --check')
    else if (id.startsWith('csharp-') || id === 'fsharp-giraffe') add('dotnet-format', '*.{cs,fs}', 'dotnet format --verify-no-changes')
    else if (id === 'elixir-phoenix') add('mix-format', '*.{ex,exs}', 'mix format --check-formatted {staged_files}')
    else if (id.startsWith('dart-')) add('dart-format', '*.dart', 'dart format --output=none --set-exit-if-changed {staged_files}')
    else if (id === 'gleam-wisp') add('gleam-format', '*.gleam', 'gleam format --check {staged_files}')
    else if (id === 'zig-http') add('zig-fmt', '*.zig', 'zig fmt --check {staged_files}')
    else if (id.startsWith('deno-')) add('deno-fmt', '*.{ts,tsx,js}', 'deno fmt --check {staged_files}')
  }
  return `# Git hooks with Lefthook (https://lefthook.dev): \`npx lefthook install\` (or brew/scoop/go install).
# Each check runs only for staged files in the app that owns them. Generated by LazyStack.
# JavaScript and Python have no built-in formatter; add one per app, for example:
#   biome:  { root: "apps/web/", glob: "*.{js,ts,tsx}", run: "npx biome check {staged_files}" }
#   ruff:   { root: "apps/api/", glob: "*.py", run: "ruff format --check {staged_files}" }

pre-commit:
  parallel: true
${commands.length ? `  commands:\n${commands.join('\n')}` : '  commands: {}'}
`
}

export const RENOVATE_JSON = JSON.stringify({
  $schema: 'https://docs.renovatebot.com/renovate-schema.json',
  extends: ['config:recommended', ':dependencyDashboard'],
  labels: ['dependencies'],
  packageRules: [
    { matchUpdateTypes: ['minor', 'patch'], groupName: 'non-major dependencies', automerge: false },
    { matchDatasources: ['docker'], matchUpdateTypes: ['major'], enabled: false }
  ]
}, null, 2) + '\n'

const slug = (value: string) => value.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '') || 'app'

/** fly.toml for one Docker app (written into the app folder, so `fly deploy` works from there). */
export function generateFlyToml(settings: ProjectSettings, app: CartApp): string {
  const healthPath = app.healthCheck?.enabled && app.healthCheck.type === 'http' ? app.healthCheck.path || '/health' : undefined
  return `# Fly.io config. Deploy from this folder: \`fly launch --no-deploy --copy-config\` once, then \`fly deploy\`.
# App names are global on Fly; change \`app\` if this one is taken. Generated by LazyStack.
app = "${slug(settings.projectName)}-${slug(app.folderName)}"
primary_region = "iad"

[build]
  dockerfile = "Dockerfile"

[env]
  PORT = "${app.port}"

[http_service]
  internal_port = ${app.port}
  force_https = true
  auto_stop_machines = "stop"
  auto_start_machines = true
  min_machines_running = 0
${healthPath ? `
[[http_service.checks]]
  grace_period = "10s"
  interval = "30s"
  method = "GET"
  timeout = "5s"
  path = "${healthPath}"
` : ''}`
}

/** Render Blueprint: one Docker web service per app, plus a managed Postgres when the stack uses one. */
export function generateRenderYaml(settings: ProjectSettings): string | undefined {
  const paths = resolveStructurePaths(settings)
  const apps = settings.apps.filter(app => !isHostOnlyTech(app.techId) && app.port > 0)
  if (!apps.length) return undefined
  const postgres = settings.databases.find(db => db.enabled && isPostgresFamily(db.type))
  const dbName = `${slug(settings.projectName)}-db`
  const services = apps.map(app => {
    const root = paths.getAppRelativePath(app.folderName, app.id, app.role)
    return `  - type: web
    name: ${slug(settings.projectName)}-${slug(app.folderName)}
    runtime: docker
    rootDir: ${root}
    dockerfilePath: ./Dockerfile
    envVars:
      - key: PORT
        value: "${app.port}"${postgres ? `
      - key: DATABASE_URL
        fromDatabase:
          name: ${dbName}
          property: connectionString` : ''}`
  })
  return `# Render Blueprint (https://render.com/docs/blueprint-spec). In the Render dashboard choose
# New → Blueprint and point it at this repository. Generated by LazyStack.
services:
${services.join('\n')}
${postgres ? `
databases:
  - name: ${dbName}
    plan: free
` : ''}`
}

/** GitLab CI: validate Compose on every pipeline, build and push app images on the default branch. */
export function generateGitlabCi(settings: ProjectSettings): string {
  const paths = resolveStructurePaths(settings)
  const apps = settings.apps.filter(app => !isHostOnlyTech(app.techId))
  const jobs = apps.map(app => `build:${app.folderName}:
  extends: .build-image
  variables:
    SERVICE: ${slug(app.folderName)}
    CONTEXT: ${paths.getAppRelativePath(app.folderName, app.id, app.role)}`).join('\n\n')
  return `# GitLab CI/CD, generated by LazyStack. Images go to this project's GitLab container registry.
stages: [validate, build]

validate:compose:
  stage: validate
  image: docker:27
  script:
    - cp -n .env.example .env || true
    - docker compose --env-file .env -f ${paths.infraDir}/docker-compose.yml config -q

.build-image:
  stage: build
  image: docker:27
  services: [docker:27-dind]
  variables:
    DOCKER_TLS_CERTDIR: "/certs"
  before_script:
    - echo "$CI_REGISTRY_PASSWORD" | docker login -u "$CI_REGISTRY_USER" --password-stdin "$CI_REGISTRY"
  script:
    - docker build -t "$CI_REGISTRY_IMAGE/$SERVICE:$CI_COMMIT_SHORT_SHA" -t "$CI_REGISTRY_IMAGE/$SERVICE:latest" "$CONTEXT"
    - docker push --all-tags "$CI_REGISTRY_IMAGE/$SERVICE"
  rules:
    - if: $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
${jobs ? `\n${jobs}\n` : ''}`
}

/** All 2.0 tooling files, keyed by path relative to the project root. */
export function generateProjectTooling(settings: ProjectSettings): Record<string, string> {
  const files: Record<string, string> = {}
  const paths = resolveStructurePaths(settings)
  const mise = generateMiseToml(settings)
  if (mise) files['mise.toml'] = mise
  files['.devcontainer/devcontainer.json'] = generateDevcontainer(settings, Boolean(mise))
  files['.editorconfig'] = EDITORCONFIG
  files['lefthook.yml'] = generateLefthook(settings)
  files['renovate.json'] = RENOVATE_JSON
  files['.gitlab-ci.yml'] = generateGitlabCi(settings)
  const render = generateRenderYaml(settings)
  if (render) files['render.yaml'] = render
  for (const app of settings.apps.filter(item => !isHostOnlyTech(item.techId) && item.port > 0)) {
    files[`${paths.getAppRelativePath(app.folderName, app.id, app.role)}/fly.toml`] = generateFlyToml(settings, app)
  }
  return files
}
