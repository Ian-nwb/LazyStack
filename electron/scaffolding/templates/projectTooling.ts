const requiredBinaries = (apps: CartApp[]) => [...new Set(apps.flatMap(app => (TECH_CATALOG.find(t => t.id === app.techId)?.requires || []).map(r => r.binary)))]

export function generateMiseToml(settings: ProjectSettings): string | undefined {
  const tools = new Map<string, string>()
  for (const binary of requiredBinaries(settings.apps)) {
    for (const [tool, version] of MISE_TOOLS[binary] || []) if (!tools.has(tool)) tools.set(tool, version)
  }
  if (!tools.size) return undefined
  const lines = [...tools].sort(([a], [b]) => a.localeCompare(b)).map(([tool, version]) => `${tool} = "${version}"`)
  return `# Toolchains for this project, pinned for every machine. Install mise (https://mise.jdx.dev),
# then run \`mise install\` in this folder: no root needed. Generated by LazyStack.
# PHP, R and OCaml are not listed: install them with your OS package manager.

[tools]
${lines.join('\n')}
`
}

export function generateDevcontainer(settings: ProjectSettings, hasMise: boolean): string {
  const features: Record<string, Record<string, string | boolean>> = {
    'ghcr.io/devcontainers/features/docker-outside-of-docker:1': {}
  }
  for (const binary of requiredBinaries(settings.apps)) {
    const feature = DEVCONTAINER_FEATURES[binary]
    if (feature) features[`ghcr.io/devcontainers/features/${feature[0]}:1`] = feature[1]
  }
  if (hasMise) features['ghcr.io/devcontainers-extra/features/mise:1'] = {}
  const ports = [
    ...settings.apps.filter(app => app.port > 0).map(app => app.port),
    ...settings.databases.filter(db => db.enabled && db.port > 0).map(db => db.port)
  ]
  return JSON.stringify({
    name: settings.projectName,
    image: 'mcr.microsoft.com/devcontainers/base:ubuntu',
    features,
    // Compose services run on the host's Docker; host networking lets apps reach them on localhost.
    runArgs: ['--network=host'],
    forwardPorts: [...new Set(ports)],
    postCreateCommand: hasMise ? 'mise trust && mise install' : 'echo "Dev container ready"',
    remoteUser: 'vscode'
  }, null, 2) + '\n'
}

