/**
 * `scripts/dev-orchestrator.mjs` in generated projects (`npm run dev`, `lazystack dev`).
 *
 * The file is a JSON config followed by a fixed, dependency-free runtime:
 *  1. starts the databases and other infrastructure in Docker and waits for their healthchecks
 *     (app containers and the gateway are not started: in dev the apps run on the host),
 *  2. runs first-boot migrations (Django, Laravel, Prisma),
 *  3. starts the apps on the host in dependency order: an app waits until the apps it connects to
 *     answer their health check (HTTP path, or the port accepting connections),
 *  4. shows a terminal dashboard (one row per service with its health, a log pane with filtering,
 *     restart, and which environment variable points where), or plain prefixed logs when output
 *     is not a terminal, in CI, or with `--plain`.
 */

export interface DevServiceConfig {
  name: string
  role: string
  port: number
  /** Project-relative app folder. */
  path: string
  cmd: string
  /** Apps (by name) that must be healthy before this one starts. */
  dependsOn: string[]
  health: { type: 'http'; url: string } | { type: 'tcp'; port: number } | null
  /** Environment variables that point at other services. */
  env: Array<{ key: string; target: string }>
  /** Databases and services this app can reach. */
  uses: string[]
}

export interface DevOrchestratorConfig {
  project: string
  /** Infrastructure services to start with Compose; null when the stack has none. */
  compose: { file: string; services: string[] } | null
  services: DevServiceConfig[]
}

/** The generated file. The runtime below is plain JavaScript; keep it free of backticks and template placeholders. */
export function renderDevOrchestrator(config: DevOrchestratorConfig): string {
  return `#!/usr/bin/env node
// Generated by LazyStack: unified dev orchestrator. Run with \`npm run dev\` or \`lazystack dev\` (--plain for plain logs).
// The CONFIG block is regenerated when the blueprint changes; the runtime below it is the same in every project.
const CONFIG = ${JSON.stringify(config, null, 2)};
${DEV_ORCHESTRATOR_RUNTIME}`
}

export const DEV_ORCHESTRATOR_RUNTIME = String.raw`
import { spawn, execSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import net from 'node:net';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const isWin = process.platform === 'win32';
const PLAIN = process.argv.includes('--plain') || !process.stdout.isTTY || !process.stdin.isTTY
  || Boolean(process.env.CI) || process.env.LAZYSTACK_PLAIN === '1';

const C = { reset: '\x1b[0m', bold: '\x1b[1m', dim: '\x1b[2m', red: '\x1b[31m', green: '\x1b[32m', yellow: '\x1b[33m', inverse: '\x1b[7m' };
const COLORS = ['\x1b[36m', '\x1b[32m', '\x1b[35m', '\x1b[33m', '\x1b[34m', '\x1b[96m', '\x1b[38;5;208m'];
const ANSI = /\x1b\[[0-9;?]*[ -\/]*[@-~]|\x1b\][^\x07]*(\x07|\x1b\\)/g;
const DEP_TIMEOUT_MS = 120000;

function loadEnv(file, into) {
  if (!existsSync(file)) return into;
  try {
    for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq > 0) into[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim().replace(/^(['"])(.*)\1$/, '$2');
    }
  } catch (error) {
    console.warn('[orchestrator] Could not parse ' + file + ': ' + error.message);
  }
  return into;
}
const localEnv = loadEnv(resolve(rootDir, '.env'), Object.assign({}, process.env));
const say = message => console.log('[orchestrator] ' + message);

// ── 1. Infrastructure ─────────────────────────────────────────────────────
const infra = { state: CONFIG.compose ? 'starting' : 'none', detail: CONFIG.compose ? CONFIG.compose.services.join(', ') : '' };

function startInfrastructure() {
  if (!CONFIG.compose) return Promise.resolve();
  const docker = isWin ? 'docker.exe' : 'docker';
  const composeArgs = ['compose', '--env-file', '.env', '-f', CONFIG.compose.file, 'up', '-d', '--wait'].concat(CONFIG.compose.services);
  say('Starting ' + CONFIG.compose.services.join(', ') + ' in Docker and waiting for their healthchecks...');
  return new Promise(done => {
    const child = spawn(docker, composeArgs, { cwd: rootDir, stdio: 'inherit' });
    child.on('close', code => {
      if (code === 0) { infra.state = 'healthy'; say('Infrastructure is healthy.\n'); }
      else { infra.state = 'failed'; infra.detail = 'docker compose exited with code ' + code; say('docker compose exited with code ' + code + '; starting the apps anyway.\n'); }
      done();
    });
    child.on('error', error => {
      infra.state = 'failed'; infra.detail = error.message;
      say('Could not run docker compose (' + error.message + '); starting the apps anyway.\n');
      done();
    });
  });
}

// ── 2. First-boot migrations ──────────────────────────────────────────────
function runMigrations() {
  for (const service of CONFIG.services) {
    const dir = resolve(rootDir, service.path);
    const run = (label, command) => {
      say(label + ' for ' + service.name + '...');
      try { execSync(command, { cwd: dir, stdio: 'inherit', env: localEnv }); }
      catch (error) { say('Notice: ' + error.message); }
    };
    if (existsSync(resolve(dir, 'manage.py'))) {
      run('Running Django migrations', (isWin ? '.venv\\Scripts\\python.exe' : '.venv/bin/python') + ' manage.py migrate --noinput');
    }
    if (existsSync(resolve(dir, 'artisan'))) {
      run('Generating the Laravel key', 'php artisan key:generate --force');
      run('Running Laravel migrations', 'php artisan migrate --force');
    }
    if (existsSync(resolve(dir, 'prisma/schema.prisma'))) {
      run('Pushing the Prisma schema', 'npx prisma db push --skip-generate');
    }
  }
}

// ── 3. Apps ───────────────────────────────────────────────────────────────
const services = CONFIG.services.map((service, index) => Object.assign({}, service, {
  color: COLORS[index % COLORS.length], state: 'waiting', detail: '', child: null, logs: [],
  queuedAt: Date.now(), startedAt: 0, restarts: 0, fails: 0, timer: null, restarting: false
}));
const byName = new Map(services.map(service => [service.name, service]));
const allLogs = [];
const MAX_LOGS = 2000;
let shuttingDown = false;

function pushLog(service, text, isErr) {
  const clean = text.replace(ANSI, '').replace(/\t/g, '  ').replace(/\r/g, '');
  const entry = { service, text: clean, isErr };
  service.logs.push(entry);
  if (service.logs.length > MAX_LOGS) service.logs.shift();
  allLogs.push(entry);
  if (allLogs.length > MAX_LOGS * 2) allLogs.shift();
  if (PLAIN) (isErr ? process.stderr : process.stdout).write(service.color + '[' + service.name + ']' + C.reset + ' ' + text + '\n');
  else redraw();
}

function setState(service, state, detail) {
  if (service.state === state && service.detail === (detail || '')) return;
  service.state = state;
  service.detail = detail || '';
  if (PLAIN) console.log(service.color + '[' + service.name + ']' + C.reset + ' ' + state + (detail ? ' · ' + detail : ''));
  else redraw();
}

function attach(stream, service, isErr) {
  if (!stream) return;
  let buffer = '';
  stream.on('data', chunk => {
    buffer += chunk.toString();
    const lines = buffer.split(/\r?\n/);
    buffer = lines.pop() || '';
    for (const line of lines) if (line.trim()) pushLog(service, line, isErr);
  });
  stream.on('end', () => { if (buffer.trim()) pushLog(service, buffer, isErr); });
}

function probe(service) {
  const health = service.health;
  if (!health) return Promise.resolve(true);
  if (health.type === 'http') {
    return fetch(health.url, { signal: AbortSignal.timeout(2000) }).then(response => response.status < 500, () => false);
  }
  return new Promise(done => {
    const socket = net.connect({ host: 'localhost', port: health.port, autoSelectFamily: true });
    const finish = ok => { socket.destroy(); done(ok); };
    socket.setTimeout(1500, () => finish(false));
    socket.once('connect', () => finish(true));
    socket.once('error', () => finish(false));
  });
}

function healthLabel(service) {
  if (!service.health) return '';
  return service.health.type === 'http' ? service.health.url : 'port ' + service.health.port;
}

function watchHealth(service) {
  clearTimeout(service.timer);
  if (!service.health) { setState(service, 'running'); return; }
  const tick = async () => {
    if (!service.child || shuttingDown) return;
    const ok = await probe(service);
    if (!service.child || shuttingDown) return;
    if (ok) {
      service.fails = 0;
      setState(service, 'healthy', healthLabel(service));
    } else if (service.state === 'healthy' || service.state === 'unhealthy') {
      service.fails += 1;
      if (service.fails >= 3) setState(service, 'unhealthy', 'no answer on ' + healthLabel(service));
    } else if (Date.now() - service.startedAt > DEP_TIMEOUT_MS) {
      setState(service, 'unhealthy', 'no answer on ' + healthLabel(service) + ' after ' + DEP_TIMEOUT_MS / 1000 + 's');
    }
    service.timer = setTimeout(tick, service.state === 'healthy' || service.state === 'unhealthy' ? 5000 : 1000);
  };
  service.timer = setTimeout(tick, 500);
}

function start(service) {
  service.startedAt = Date.now();
  service.fails = 0;
  setState(service, 'starting', service.cmd);
  const child = spawn(service.cmd, {
    cwd: resolve(rootDir, service.path),
    env: Object.assign({}, localEnv, { PORT: service.port > 0 ? String(service.port) : localEnv.PORT }),
    shell: true,
    stdio: ['ignore', 'pipe', 'pipe'],
    // Its own process group on POSIX, so stopping it also stops what it spawned (npm, vite, nodemon...).
    detached: !isWin
  });
  service.child = child;
  attach(child.stdout, service, false);
  attach(child.stderr, service, true);
  child.on('error', error => pushLog(service, 'could not start: ' + error.message, true));
  child.on('exit', (code, signal) => {
    if (service.child === child) service.child = null;
    clearTimeout(service.timer);
    if (service.restarting || shuttingDown) return;
    const result = code === null ? signal : 'code ' + code;
    pushLog(service, 'exited with ' + result, code !== 0);
    setState(service, code === 0 ? 'exited' : 'failed', 'exited with ' + result);
  });
  watchHealth(service);
}

function stop(service) {
  const child = service.child;
  if (!child) return Promise.resolve();
  return new Promise(done => {
    const timeout = setTimeout(() => {
      try { if (!isWin) process.kill(-child.pid, 'SIGKILL'); } catch (error) { /* already gone */ }
      done();
    }, 5000);
    child.once('exit', () => { clearTimeout(timeout); done(); });
    try {
      if (isWin) spawn('taskkill', ['/pid', String(child.pid), '/f', '/t']);
      else process.kill(-child.pid, 'SIGTERM');
    } catch (error) {
      try { child.kill('SIGTERM'); } catch (ignored) { /* already gone */ }
    }
  });
}

async function restart(service) {
  if (service.restarting) return;
  service.restarting = true;
  setState(service, 'restarting');
  await stop(service);
  service.restarting = false;
  service.restarts += 1;
  pushLog(service, '── restarted (' + service.restarts + ') ──', false);
  start(service);
}

const READY = ['healthy', 'running', 'exited', 'failed', 'unhealthy'];
function schedule() {
  for (const service of services) {
    if (service.state !== 'waiting' || shuttingDown) continue;
    const pending = service.dependsOn.filter(name => byName.has(name) && READY.indexOf(byName.get(name).state) < 0);
    if (!pending.length) { start(service); continue; }
    if (Date.now() - service.queuedAt > DEP_TIMEOUT_MS) {
      pushLog(service, 'starting without ' + pending.join(', ') + ' (not healthy after ' + DEP_TIMEOUT_MS / 1000 + 's)', true);
      start(service);
      continue;
    }
    setState(service, 'waiting', 'for ' + pending.join(', '));
  }
}

// ── 4. Dashboard ──────────────────────────────────────────────────────────
const ui = { selected: 0, filter: '', typing: false, showEnv: false, dirty: true };
const MARK = { waiting: '○', starting: '◐', restarting: '◐', healthy: '●', running: '●', unhealthy: '▲', failed: '✕', exited: '■', none: ' ' };
const TONE = { healthy: C.green, running: C.green, starting: C.yellow, restarting: C.yellow, waiting: C.dim, unhealthy: C.red, failed: C.red, exited: C.dim, none: C.dim };

const visibleLength = text => text.replace(ANSI, '').length;
function fit(text, width) {
  let out = '';
  let seen = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '\x1b') {
      const match = text.slice(i).match(/^\x1b\[[0-9;?]*[ -\/]*[@-~]/);
      if (match) { out += match[0]; i += match[0].length - 1; continue; }
    }
    if (seen >= width) break;
    out += text[i];
    seen += 1;
  }
  return out + C.reset;
}
const padEnd = (text, width) => text + ' '.repeat(Math.max(0, width - visibleLength(text)));

function redraw() { ui.dirty = true; }

function serviceRow(service, index, nameWidth) {
  const selected = ui.selected === index + 1;
  const tone = TONE[service.state] || '';
  const port = service.port > 0 ? ':' + service.port : '';
  const deps = service.dependsOn.length ? 'after ' + service.dependsOn.join(', ') : '';
  const line = ' ' + (index < 9 ? String(index + 1) : ' ') + ' ' + tone + MARK[service.state] + ' ' + padEnd(service.name, nameWidth) + ' ' + padEnd(service.state, 10) + C.reset
    + ' ' + padEnd(port, 6) + ' ' + C.dim + padEnd(deps, 22) + ' ' + (service.detail || '') + C.reset;
  return selected ? C.inverse + line.replace(/\x1b\[0m/g, C.reset + C.inverse) : line;
}

function envLines(list) {
  const out = [];
  for (const service of list) {
    out.push(C.bold + service.name + C.reset + C.dim + '  ' + service.path + C.reset);
    if (!service.env.length && !service.uses.length) out.push('  ' + C.dim + 'no connections' + C.reset);
    for (const link of service.env) {
      const target = byName.get(link.target);
      out.push('  ' + link.key + ' → ' + link.target + (target && target.port > 0 ? ' (:' + target.port + ')' : '') + (localEnv[link.key] ? C.dim + '  = ' + localEnv[link.key] + C.reset : ''));
    }
    if (service.uses.length) out.push('  ' + C.dim + 'uses ' + service.uses.join(', ') + C.reset);
  }
  return out;
}

function draw() {
  ui.dirty = false;
  const width = process.stdout.columns || 100;
  const height = process.stdout.rows || 30;
  const nameWidth = Math.max(14, ...services.map(service => service.name.length));
  const lines = [];
  lines.push(C.bold + ' LazyStack dev · ' + CONFIG.project + C.reset + C.dim + '   ' + services.filter(s => s.state === 'healthy' || s.state === 'running').length + '/' + services.length + ' up' + C.reset);
  lines.push(C.dim + '─'.repeat(width) + C.reset);
  const allRow = ' 0   ' + padEnd('all logs', nameWidth) + ' ' + (infra.state === 'none' ? '' : C.dim + 'docker: ' + (TONE[infra.state] || '') + infra.state + C.reset + C.dim + (infra.detail ? ' · ' + infra.detail : '') + C.reset);
  lines.push(ui.selected === 0 ? C.inverse + allRow.replace(/\x1b\[0m/g, C.reset + C.inverse) : allRow);
  services.forEach((service, index) => lines.push(serviceRow(service, index, nameWidth)));
  lines.push(C.dim + '─'.repeat(width) + C.reset);

  const current = ui.selected === 0 ? null : services[ui.selected - 1];
  const title = ui.showEnv ? 'Environment: ' + (current ? current.name : 'all services') : 'Logs: ' + (current ? current.name : 'all');
  const filterText = ui.showEnv ? '' : ui.typing ? '  filter: ' + ui.filter + '▏' : ui.filter ? '  filter: "' + ui.filter + '" (/ to change, Esc in filter to clear)' : '';
  lines.push(C.bold + ' ' + title + C.reset + C.yellow + filterText + C.reset);

  const footer = C.dim + ' ↑↓/0-9 select · r restart · / filter · e env · c clear · q quit' + C.reset;
  const room = Math.max(1, height - lines.length - 1);
  let body;
  if (ui.showEnv) {
    body = envLines(current ? [current] : services);
  } else {
    const needle = ui.filter.toLowerCase();
    const source = current ? current.logs : allLogs;
    body = [];
    for (let i = source.length - 1; i >= 0 && body.length < room; i--) {
      const entry = source[i];
      if (needle && entry.text.toLowerCase().indexOf(needle) < 0) continue;
      body.unshift((current ? '' : entry.service.color + entry.service.name + C.reset + ' ') + entry.text);
    }
  }
  body = body.slice(-room);
  while (body.length < room) body.push('');
  const screen = lines.concat(body.map(line => ' ' + line), [footer]).slice(0, height);
  process.stdout.write('\x1b[H' + screen.map(line => fit(line, width) + '\x1b[K').join('\n'));
}

function enterDashboard() {
  process.stdout.write('\x1b[?1049h\x1b[?25l');
  process.stdin.setRawMode(true);
  process.stdin.setEncoding('utf8');
  process.stdin.resume();
  process.stdin.on('data', chunk => splitKeys(chunk).forEach(onKey));
  process.stdout.on('resize', redraw);
  setInterval(() => { if (ui.dirty) draw(); }, 80);
}

function leaveDashboard() {
  if (PLAIN) return;
  try { process.stdin.setRawMode(false); } catch (error) { /* not a TTY */ }
  process.stdout.write('\x1b[?25h\x1b[?1049l');
}

// Keys typed quickly (or pasted) arrive in one chunk: split it into single keys and escape sequences.
function splitKeys(chunk) {
  const keys = [];
  for (let i = 0; i < chunk.length; i++) {
    if (chunk[i] === '\x1b' && chunk[i + 1] === '[') {
      let end = i + 2;
      while (end < chunk.length && !/[A-Za-z~]/.test(chunk[end])) end++;
      keys.push(chunk.slice(i, end + 1));
      i = end;
    } else {
      keys.push(chunk[i]);
    }
  }
  return keys;
}

function onKey(key) {
  if (key === '\x03') return shutdown('Ctrl+C');
  if (ui.typing) {
    if (key === '\r' || key === '\n') ui.typing = false;
    else if (key === '\x1b') { ui.typing = false; ui.filter = ''; }
    else if (key === '\x7f' || key === '\b') ui.filter = ui.filter.slice(0, -1);
    else if (key >= ' ' && key.length === 1) ui.filter += key;
    return redraw();
  }
  const current = ui.selected === 0 ? null : services[ui.selected - 1];
  if (key === 'q') return shutdown('q');
  if (key === '\x1b[A' || key === 'k') ui.selected = Math.max(0, ui.selected - 1);
  else if (key === '\x1b[B' || key === 'j') ui.selected = Math.min(services.length, ui.selected + 1);
  else if (/^[0-9]$/.test(key)) ui.selected = Math.min(services.length, Number(key));
  else if (key === 'r') (current ? [current] : services).forEach(service => { if (service.child || service.state === 'failed' || service.state === 'exited') restart(service); });
  else if (key === '/') { ui.typing = true; ui.filter = ''; }
  else if (key === 'e') ui.showEnv = !ui.showEnv;
  else if (key === 'c') { if (current) current.logs.length = 0; else allLogs.length = 0; }
  else if (key === '\x1b') ui.filter = '';
  redraw();
}

async function shutdown(reason) {
  if (shuttingDown) return;
  shuttingDown = true;
  leaveDashboard();
  console.log('\n' + C.bold + '[orchestrator] Stopping all apps (' + reason + ')...' + C.reset);
  if (CONFIG.compose) console.log(C.dim + '[orchestrator] Databases keep running; stop them with: docker compose -f ' + CONFIG.compose.file + ' stop' + C.reset);
  await Promise.all(services.map(stop));
  process.exit(0);
}

process.on('SIGINT', () => shutdown('SIGINT'));
process.on('SIGTERM', () => shutdown('SIGTERM'));
process.on('uncaughtException', error => { leaveDashboard(); console.error('[orchestrator] Fatal error:', error); process.exit(1); });

async function main() {
  console.log(C.bold + 'LazyStack dev · ' + CONFIG.project + C.reset);
  await startInfrastructure();
  runMigrations();
  if (!services.length) { say('No apps to start.'); return; }
  if (!PLAIN) enterDashboard();
  else say('Starting ' + services.length + ' app(s) in dependency order. Ctrl+C stops them.');
  schedule();
  setInterval(schedule, 500);
}

main().catch(error => {
  leaveDashboard();
  console.error('[orchestrator] Fatal error:', error);
  process.exit(1);
});
`
