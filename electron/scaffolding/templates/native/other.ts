import { Files, GITIGNORE, json, NativeContext, readme, shell } from './context'

function denoNative(c: NativeContext): Files {
  const port = c.port || 8000
  return {
    'deno.json': json({
      tasks: {
        dev: 'deno run --watch --allow-net --allow-env main.ts',
        start: 'deno run --allow-net --allow-env main.ts',
        test: 'deno test --allow-net --allow-env'
      },
      imports: { '@std/assert': 'jsr:@std/assert@1' }
    }),
    'main.ts': `export function handler(req: Request): Response {
  const { pathname } = new URL(req.url);
  if (pathname === "/health") return Response.json({ status: "healthy" });
  if (pathname === "/") return Response.json({ service: "${c.name}", runtime: "Deno", status: "online" });
  return Response.json({ error: "not found" }, { status: 404 });
}

if (import.meta.main) {
  const port = Number(Deno.env.get("PORT") ?? ${port});
  Deno.serve({ port, hostname: "0.0.0.0" }, handler);
}
`,
    'main_test.ts': `import { assertEquals } from "@std/assert";
import { handler } from "./main.ts";

Deno.test("GET /health reports healthy", async () => {
  const res = handler(new Request("http://localhost/health"));
  assertEquals(res.status, 200);
  assertEquals(await res.json(), { status: "healthy" });
});
`,
    '.gitignore': GITIGNORE.generic,
    'README.md': readme(`${c.name} (Deno)`, 'Deno HTTP service generated by LazyStack, following the `deno init` layout.', [
      ['Layout', '- `main.ts`: request handler and server\n- `main_test.ts`: `deno test` tests\n- `deno.json`: tasks and import map'],
      ['Develop', shell('deno task dev\ndeno task test')]
    ])
  }
}

