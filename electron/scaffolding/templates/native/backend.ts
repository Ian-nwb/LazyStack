import { Files, GITIGNORE, json, NativeContext, readme, shell } from './context'

function aspnet(c: NativeContext): Files {
  const ns = c.pascal
  return {
    [`${c.name}.csproj`]: `<Project Sdk="Microsoft.NET.Sdk.Web">\n\n  <PropertyGroup>\n    <TargetFramework>net9.0</TargetFramework>\n    <Nullable>enable</Nullable>\n    <ImplicitUsings>enable</ImplicitUsings>\n    <RootNamespace>${ns}</RootNamespace>\n    <AssemblyName>app</AssemblyName>\n  </PropertyGroup>\n\n</Project>\n`,
    'Program.cs': `using ${ns}.Endpoints;

var builder = WebApplication.CreateBuilder(args);

var port = Environment.GetEnvironmentVariable("PORT") ?? "${c.port || 5000}";
builder.WebHost.UseUrls($"http://0.0.0.0:{port}");

builder.Services.AddProblemDetails();

var app = builder.Build();

app.UseExceptionHandler();
app.MapStatusEndpoints();

app.Run();

// Exposed for WebApplicationFactory-based integration tests.
public partial class Program { }
`,
    'Endpoints/StatusEndpoints.cs': `namespace ${ns}.Endpoints;

public static class StatusEndpoints
{
    public static IEndpointRouteBuilder MapStatusEndpoints(this IEndpointRouteBuilder app)
    {
        app.MapGet("/", () => new
        {
            service = "${c.name}",
            framework = "ASP.NET Core",
            status = "online",
            runtime = System.Runtime.InteropServices.RuntimeInformation.FrameworkDescription
        });

        app.MapGet("/health", () => Results.Ok(new { status = "healthy" }));
        return app;
    }
}
`,
    'appsettings.json': json({ Logging: { LogLevel: { Default: 'Information', 'Microsoft.AspNetCore': 'Warning' } }, AllowedHosts: '*' }),
    'appsettings.Development.json': json({ Logging: { LogLevel: { Default: 'Information', 'Microsoft.AspNetCore': 'Warning' } } }),
    'Properties/launchSettings.json': json({
      $schema: 'https://json.schemastore.org/launchsettings.json',
      profiles: { http: { commandName: 'Project', dotnetRunMessages: true, launchBrowser: false, applicationUrl: `http://localhost:${c.port || 5000}`, environmentVariables: { ASPNETCORE_ENVIRONMENT: 'Development' } } }
    }),
    [`${c.name}.http`]: `@host = http://localhost:${c.port || 5000}\n\nGET {{host}}/health\nAccept: application/json\n`,
    '.gitignore': GITIGNORE.dotnet,
    'README.md': readme(`${c.name} (ASP.NET Core)`, 'ASP.NET Core minimal API generated by LazyStack, following the `dotnet new web` layout.', [
      ['Layout', `- \`Program.cs\`: host setup and middleware\n- \`Endpoints/\`: endpoint groups mapped with extension methods\n- \`appsettings*.json\`: configuration\n- \`${c.name}.http\`: requests for the VS Code / Rider HTTP client`],
      ['Develop', shell('dotnet watch run')],
      ['Publish', shell('dotnet publish -c Release -o out && dotnet out/app.dll')]
    ])
  }
}

