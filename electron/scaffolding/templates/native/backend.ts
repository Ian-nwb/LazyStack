function phoenix(c: NativeContext): Files {
  const app = c.snake
  const mod = c.pascal
  const web = `${mod}Web`
  return {
    'mix.exs': `defmodule ${mod}.MixProject do
  use Mix.Project

  def project do
    [
      app: :${app},
      version: "0.1.0",
      elixir: "~> 1.15",
      elixirc_paths: elixirc_paths(Mix.env()),
      start_permanent: Mix.env() == :prod,
      aliases: aliases(),
      deps: deps(),
      releases: [server: [applications: [${app}: :permanent]]]
    ]
  end

  def application do
    [
      mod: {${mod}.Application, []},
      extra_applications: [:logger, :runtime_tools]
    ]
  end

  defp elixirc_paths(:test), do: ["lib", "test/support"]
  defp elixirc_paths(_), do: ["lib"]

  defp deps do
    [
      {:phoenix, "~> 1.7"},
      {:jason, "~> 1.4"},
      {:bandit, "~> 1.5"}
    ]
  end

  defp aliases do
    [setup: ["deps.get"]]
  end
end
`,
    '.formatter.exs': '[\n  import_deps: [:phoenix],\n  inputs: ["*.{ex,exs}", "{config,lib,test}/**/*.{ex,exs}"]\n]\n',
    'config/config.exs': `import Config

config :${app}, ${web}.Endpoint,
  url: [host: "localhost"],
  adapter: Bandit.PhoenixAdapter,
  render_errors: [formats: [json: ${web}.ErrorJSON], layout: false]

config :logger, :console, format: "$time $metadata[$level] $message\\n", metadata: [:request_id]

config :phoenix, :json_library, Jason

import_config "#{config_env()}.exs"
`,
    'config/dev.exs': `import Config

config :${app}, ${web}.Endpoint,
  http: [ip: {0, 0, 0, 0}, port: ${c.port || 4000}],
  check_origin: false,
  code_reloader: true,
  debug_errors: true,
  secret_key_base: "dev-secret-key-base-change-me-dev-secret-key-base-change-me-0123456789abcdef"

config :phoenix, :plug_init_mode, :runtime
`,
    'config/test.exs': `import Config

config :${app}, ${web}.Endpoint,
  http: [ip: {127, 0, 0, 1}, port: 4002],
  secret_key_base: "test-secret-key-base-test-secret-key-base-test-secret-key-base-0123456789",
  server: false

config :logger, level: :warning
config :phoenix, :plug_init_mode, :runtime
`,
    'config/prod.exs': 'import Config\n\nconfig :logger, level: :info\n',
    'config/runtime.exs': `import Config

if config_env() == :prod do
  secret_key_base =
    System.get_env("SECRET_KEY_BASE") ||
      "prod-secret-placeholder-set-SECRET_KEY_BASE-prod-secret-placeholder-0123456789abcdef"

  config :${app}, ${web}.Endpoint,
    http: [ip: {0, 0, 0, 0}, port: String.to_integer(System.get_env("PORT") || "${c.port || 4000}")],
    secret_key_base: secret_key_base,
    server: true
end
`,
    [`lib/${app}.ex`]: `defmodule ${mod} do\n  @moduledoc """\n  ${mod} keeps the contexts that define your domain and business logic.\n  """\nend\n`,
    [`lib/${app}/application.ex`]: `defmodule ${mod}.Application do
  @moduledoc false
  use Application

  @impl true
  def start(_type, _args) do
    children = [
      ${web}.Endpoint
    ]

    Supervisor.start_link(children, strategy: :one_for_one, name: ${mod}.Supervisor)
  end

  @impl true
  def config_change(changed, _new, removed) do
    ${web}.Endpoint.config_change(changed, removed)
    :ok
  end
end
`,
    [`lib/${app}_web.ex`]: `defmodule ${web} do
  @moduledoc """
  Entrypoint for defining the web interface (controllers, routers).
  """

  def router do
    quote do
      use Phoenix.Router, helpers: false
      import Plug.Conn
      import Phoenix.Controller
    end
  end

  def controller do
    quote do
      use Phoenix.Controller, formats: [:json]
      import Plug.Conn
    end
  end

  defmacro __using__(which) when is_atom(which) do
    apply(__MODULE__, which, [])
  end
end
`,
    [`lib/${app}_web/endpoint.ex`]: `defmodule ${web}.Endpoint do
  use Phoenix.Endpoint, otp_app: :${app}

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug ${web}.Router
end
`,
    [`lib/${app}_web/router.ex`]: `defmodule ${web}.Router do
  use ${web}, :router

  pipeline :api do
    plug :accepts, ["json"]
  end

  scope "/", ${web} do
    pipe_through :api

    get "/", StatusController, :index
    get "/health", StatusController, :health
  end
end
`,
    [`lib/${app}_web/controllers/status_controller.ex`]: `defmodule ${web}.StatusController do
  use ${web}, :controller

  def index(conn, _params) do
    json(conn, %{service: "${c.name}", framework: "Phoenix", status: "online"})
  end

  def health(conn, _params) do
    json(conn, %{status: "healthy"})
  end
end
`,
    [`lib/${app}_web/controllers/error_json.ex`]: `defmodule ${web}.ErrorJSON do
  def render(template, _assigns) do
    %{errors: %{detail: Phoenix.Controller.status_message_from_template(template)}}
  end
end
`,
    'test/test_helper.exs': 'ExUnit.start()\n',
    'test/support/conn_case.ex': `defmodule ${web}.ConnCase do
  use ExUnit.CaseTemplate

  using do
    quote do
      @endpoint ${web}.Endpoint
      import Plug.Conn
      import Phoenix.ConnTest
    end
  end

  setup _tags do
    {:ok, conn: Phoenix.ConnTest.build_conn()}
  end
end
`,
    [`test/${app}_web/controllers/status_controller_test.exs`]: `defmodule ${web}.StatusControllerTest do
  use ${web}.ConnCase

  test "GET /health", %{conn: conn} do
    conn = get(conn, "/health")
    assert json_response(conn, 200) == %{"status" => "healthy"}
  end
end
`,
    '.gitignore': GITIGNORE.elixir,
    'README.md': readme(`${c.name} (Phoenix)`, 'Phoenix JSON API generated by LazyStack, matching `mix phx.new --no-html --no-assets --no-ecto`.', [
      ['Layout', `- \`lib/${app}/\`: application and business contexts\n- \`lib/${app}_web/\`: endpoint, router and controllers\n- \`config/\`: per-environment configuration (\`runtime.exs\` reads \`PORT\`/\`SECRET_KEY_BASE\` in prod)\n- \`test/\`: ExUnit tests with \`ConnCase\``],
      ['Develop', shell('mix setup\nmix phx.server\nmix test')],
      ['Release', shell('MIX_ENV=prod mix release server\n_build/prod/rel/server/bin/server start')]
    ])
  }
}

