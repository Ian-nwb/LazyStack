import { createContext, Files, GITIGNORE, mergeMissing, NativeContext, readme } from './context'
import { goExtras, goStarters } from './go'
import { pythonExtras, pythonStarters } from './python'
import { jsExtras, jsStarters } from './javascript'
import { backendExtras, backendStarters } from './backend'
import { otherExtras, otherStarters } from './other'
import { jvmExtras, jvmStarters } from './jvm'
import { rustExtras, rustStarters } from './rust'
import { jsFrameworkStarters } from './jsFrameworks'
import { languageStarters } from './languages'

type Starter = (c: NativeContext) => Files
type Extra = (c: NativeContext, files: Files) => Files | void

/**
 * Full framework-native starters. These replace the legacy single-file templates in
 * appTemplates.ts and mirror what the framework's own initializer generates.
 */
const STARTERS: Record<string, Starter> = {
  ...rustStarters,
  ...jvmStarters,
  ...goStarters,
  ...pythonStarters,
  ...jsStarters,
  ...backendStarters,
  ...otherStarters,
  ...jsFrameworkStarters,
  ...languageStarters
}

/**
 * Additions layered on top of an existing starter (legacy or native). Extras only add
 * files that are missing, or patch manifests in place; they never replace source files.
 */
const EXTRAS: Record<string, Extra> = {
  ...rustExtras,
  ...jvmExtras,
  ...goExtras,
  ...pythonExtras,
  ...jsExtras,
  ...backendExtras,
  ...otherExtras
}

/** Profiles that keep their dedicated legacy implementation instead of the native starter. */
const PROFILE_OVERRIDES = new Set(['python-fastapi:api-service'])

export function hasNativeStarter(techId: string): boolean {
  return techId in STARTERS
}

export function applyNativeScaffold(
  techId: string,
  folderName: string,
  port: number,
  isTS: boolean,
  starterProfile: 'minimal' | 'api-service',
  legacy: () => Files
): Files {
  const c = createContext(techId, folderName, port, isTS, starterProfile)
  const useNative = STARTERS[techId] && !PROFILE_OVERRIDES.has(`${techId}:${starterProfile}`)
  const files: Files = useNative ? STARTERS[techId](c) : legacy()
  const extra = EXTRAS[techId]?.(c, files)
  if (extra) mergeMissing(files, extra)
  if (!('.gitignore' in files)) files['.gitignore'] = GITIGNORE.generic
  if (!('README.md' in files)) files['README.md'] = readme(folderName, `Generated by LazyStack (${techId}).`, [])
  return files
}
