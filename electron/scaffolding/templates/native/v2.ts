/** Multi-line run instructions for the project README. */
export function v2ReadmeRunCommand(techId: string, port: number): string | undefined {
  const venv = 'python -m venv .venv && source .venv/bin/activate\npip install -r requirements.txt\n'
  switch (techId) {
    case 'python-django-ninja': return `${venv}python manage.py migrate\npython manage.py runserver 0.0.0.0:${port}`
    case 'python-dash': return `${venv}python app.py`
    case 'python-fasthtml': return `${venv}python main.py`
    case 'mkdocs-material': return `${venv}mkdocs serve -a 0.0.0.0:${port}`
    case 'php-slim': return 'composer install\ncomposer start'
    case 'ruby-sinatra': return `bundle install\nbundle exec rackup -o 0.0.0.0 -p ${port}`
    case 'perl-mojolicious': return `cpanm --installdeps .\nmorbo -l http://*:${port} app.pl`
    case 'go-templ-htmx': return 'go install github.com/a-h/templ/cmd/templ@latest\ntempl generate && go run .'
    case 'dart-frog': return `dart pub global activate dart_frog_cli\ndart pub get\ndart_frog dev --port ${port}`
  }
  const single = v2DevCommand(techId, port, 'python')
  if (!single) return undefined
  return /^(npm|alpine)/.test(single) ? `npm install\n${single}` : single
}
