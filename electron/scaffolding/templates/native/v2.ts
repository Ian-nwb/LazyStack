    'router.go': `package main

import (
	"encoding/json"
	"net/http"
	"strconv"
	"sync/atomic"

	"github.com/a-h/templ"
)

var clicks atomic.Int64

// NewRouter serves the page, an HTMX fragment endpoint and /health.
func NewRouter() http.Handler {
	mux := http.NewServeMux()
	mux.Handle("GET /", templ.Handler(Page("${c.name}")))
	mux.HandleFunc("POST /clicks", func(w http.ResponseWriter, r *http.Request) {
		Counter(strconv.FormatInt(clicks.Add(1), 10)).Render(r.Context(), w)
	})
	mux.HandleFunc("GET /health", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(map[string]string{"status": "healthy"})
	})
	return mux
}
`,
    'components.templ': `package main

templ Page(title string) {
	<!DOCTYPE html>
	<html lang="en">
		<head>
			<meta charset="utf-8"/>
			<meta name="viewport" content="width=device-width, initial-scale=1"/>
			<title>{ title }</title>
			<script src="https://unpkg.com/htmx.org@2.0.4"></script>
		</head>
		<body>
			<h1>{ title }</h1>
			<p>Go + templ + HTMX, generated by LazyStack.</p>
			<button hx-post="/clicks" hx-target="#count" hx-swap="outerHTML">Click me</button>
			@Counter("0")
		</body>
	</html>
}

templ Counter(count string) {
	<span id="count">{ count }</span>
}
`,
