import { Files, GITIGNORE, json, NativeContext, patchPackageJson, readme, shell } from './context'

const npmDev = (c: NativeContext, devCmd = 'npm run dev') => shell(`npm install\n${devCmd}`)

/** Ensures `npm start` exists: the generated Node Dockerfile always runs `npm start`. */
const ensureStart = (files: Files, start: string) => patchPackageJson(files, pkg => {
  pkg.scripts = pkg.scripts || {}
  if (!pkg.scripts.start) pkg.scripts.start = start
})

const viteSpaExtras = (c: NativeContext, files: Files, framework: string): Files => {
  const port = c.port || 5173
  ensureStart(files, `vite preview --host 0.0.0.0 --port ${port}`)
  patchPackageJson(files, pkg => {
    pkg.scripts.preview = pkg.scripts.preview || 'vite preview'
  })
  const additions: Files = {
    'public/favicon.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="6" fill="#18181b"/><text x="16" y="21" font-size="14" text-anchor="middle" fill="#a78bfa" font-family="sans-serif">${c.name.slice(0, 2).toUpperCase()}</text></svg>\n`,
    'src/assets/.gitkeep': '',
    'src/components/.gitkeep': '',
    '.gitignore': GITIGNORE.node,
    'README.md': readme(`${c.name} (${framework})`, `${framework} app generated by LazyStack, following the \`npm create vite\` layout.`, [
      ['Layout', '- `index.html`: Vite entry\n- `src/`: application code (`components/`, `assets/`)\n- `public/`: files served as-is'],
      ['Develop', npmDev(c)],
      ['Build & preview', shell('npm run build\nnpm start   # serves dist/ with vite preview')]
    ])
  }
  if (c.isTS && Object.keys(files).some(file => /\.tsx?$/.test(file))) additions['src/vite-env.d.ts'] = '/// <reference types="vite/client" />\n'
  return additions
}

