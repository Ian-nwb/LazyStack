const npmDev = (devCmd = 'npm run dev') => shell(`npm install\n${devCmd}`)

const head = (name: string, extra: Record<string, unknown>) => ({ name, version: '0.1.0', private: true, ...extra })

// --- Vite based single page apps -------------------------------------------------------------

interface ViteSpa {
  label: string
  entryHtml: string
  entry: string
  plugin: { importLine: string; call: string }
  deps: Record<string, string>
  devDeps: Record<string, string>
  files: Files
}

function viteSpa(c: NativeContext, spec: ViteSpa): Files {
  const port = c.port || 5173
  return {
    'package.json': json(head(c.name, {
      type: 'module',
      scripts: {
        dev: `vite --host 0.0.0.0 --port ${port}`,
        build: 'vite build',
        preview: `vite preview --host 0.0.0.0 --port ${port}`,
        start: `vite preview --host 0.0.0.0 --port ${port}`
      },
      dependencies: spec.deps,
      devDependencies: { vite: '^6.0.0', ...spec.devDeps }
    })),
    'vite.config.js': `import { defineConfig } from 'vite';\n${spec.plugin.importLine}\n\nexport default defineConfig({\n  plugins: [${spec.plugin.call}],\n  server: { host: '0.0.0.0', port: ${port} },\n  preview: { host: '0.0.0.0', port: ${port}, allowedHosts: true }\n});\n`,
    'index.html': `<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n    <link rel="icon" href="/favicon.svg" />\n    <title>${c.name}</title>\n  </head>\n  <body>\n    <div id="app"></div>\n    <script type="module" src="${spec.entryHtml}"></script>\n  </body>\n</html>\n`,
    'public/favicon.svg': `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="6" fill="#18181b"/><text x="16" y="21" font-size="14" text-anchor="middle" fill="#a78bfa" font-family="sans-serif">${c.name.slice(0, 2).toUpperCase()}</text></svg>\n`,
    'src/style.css': `:root {\n  font-family: system-ui, sans-serif;\n  color-scheme: light dark;\n}\n\nbody {\n  margin: 0;\n  display: grid;\n  min-height: 100vh;\n  place-items: center;\n}\n\nmain {\n  text-align: center;\n}\n`,
    'src/assets/.gitkeep': '',
    'src/components/.gitkeep': '',
    ...spec.files,
    '.gitignore': GITIGNORE.node,
    'README.md': readme(`${c.name} (${spec.label})`, `${spec.label} app generated by LazyStack, following the \`npm create vite\` layout.`, [
      ['Layout', '- `index.html`: Vite entry\n- `src/`: application code (`components/`, `assets/`)\n- `public/`: files served as-is'],
      ['Develop', npmDev()],
      ['Build & preview', shell('npm run build\nnpm start   # serves dist/ with vite preview')]
    ])
  }
}

