// ── PHP skeleton packages ───────────────────────────────────────────────────────────────────────
// CodeIgniter, CakePHP and Laravel ship their application skeleton as a Composer package. The
// starter requires it and, after every install, copies in whatever skeleton files the project does
// not have yet, so the official layout arrives complete while the files LazyStack wrote win.
const skeletonCopier = (sources: string[], after = '') => `<?php
// Copies the framework's application skeleton into this project, never overwriting existing files.
// Runs after composer install/update (see composer.json "scripts").
$copy = function (string $from, string $to) use (&$copy): void {
    if (is_dir($from)) {
        if (!is_dir($to)) mkdir($to, 0775, true);
        foreach (scandir($from) as $entry) {
            if ($entry !== '.' && $entry !== '..') $copy("$from/$entry", "$to/$entry");
        }
    } elseif (!file_exists($to)) {
        copy($from, $to);
        if (str_ends_with($to, '/spark') || str_ends_with($to, '/cake') || str_ends_with($to, '/artisan')) chmod($to, 0755);
    }
};
foreach (${JSON.stringify(sources).replace(/"/g, "'")} as $entry) {
    [$from, $to] = explode('=>', $entry);
    if (file_exists(__DIR__ . '/' . $from)) $copy(__DIR__ . '/' . $from, __DIR__ . '/' . $to);
}
${after}`

const phpRuntime = (port: number, serve: string, extra = '') => `FROM composer:2 AS vendor
WORKDIR /app
COPY . .
RUN composer install --no-interaction --no-progress --prefer-dist --ignore-platform-req=ext-intl
${extra}
FROM php:8.4-cli-alpine
RUN apk add --no-cache icu-dev && docker-php-ext-install intl
WORKDIR /app
COPY --from=vendor /app /app
ENV PORT=${port}
EXPOSE ${port}
CMD ${serve}
`

