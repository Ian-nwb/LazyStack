function gooseHttp(c: NativeContext): Files {
  const port = c.port || 8080
  return {
    'src/main.goose': String.raw`// ${c.name}: HTTP service in Goose, generated by LazyStack.
//
// Goose has no networking in its standard library yet, so src/http.c holds a
// small POSIX socket layer (listed in src/main.build) and the extern fns
// below bind it. Routing, parsing and responses are plain Goose.
//
//   goose build -o build/server src/main.goose && ./build/server
//   goose run src/main.goose -- --self-test

import std;
import os;

extern fn gh_listen(port: i32) -> i32;
extern fn gh_accept(server: i32) -> i32;
extern fn gh_recv(fd: i32, buf: u8[:]) -> i64;
extern fn gh_send(fd: i32, data: const u8[:]);
extern fn gh_close(fd: i32);

fn port_from_env() -> i32 {
    var value: u8[>..] = [];
    guard env("PORT", value) else { return ${port}; }
    let n, ok = parse_int(value);
    guard ok && n > 0 && n < 65536 else { return ${port}; }
    return n as i32;
}

// Writes the JSON body for one request and returns its HTTP status.
fn route(method: const u8[:], path: const u8[:], body: u8[>..]&) -> i32 {
    guard method == "GET" else {
        body.append("{\"error\":\"method not allowed\"}");
        return 405;
    }
    if path == "/" {
        body.append("{\"service\":\"${c.name}\",\"framework\":\"Goose\",\"status\":\"online\"}");
        return 200;
    }
    if path == "/health" {
        body.append("{\"status\":\"healthy\"}");
        return 200;
    }
    body.append("{\"error\":\"not found\"}");
    return 404;
}

fn reason(status: i32) -> const u8[:] {
    match status { 200 => "OK", 404 => "Not Found", 405 => "Method Not Allowed", _ => "Bad Request" }
}

// Answers one connection: parse the request line, route, write, close.
fn handle(client: i32, buf: u8[>..]&) {
    let n = gh_recv(client, buf);
    let request = buf[..n];
    let eol = find(request, "\r\n");
    let line = if eol < 0 { request } else { request[..eol] };
    let parts = words(line);

    var body: u8[>..] = [];
    var status: i32 = 400;
    if parts.len >= 2 {
        let target = parts[1];
        let q = position(target, '?');
        let path = if q < 0 { target } else { target[..q] };
        status = route(parts[0], path, body);
    } else {
        body.append("{\"error\":\"bad request\"}");
    }

    var response: u8[>..] = [];
    format(response, "HTTP/1.1 ", status, " ", reason(status), "\r\n");
    format(response, "Content-Type: application/json\r\nContent-Length: ", body.len, "\r\n");
    format(response, "Connection: close\r\n\r\n", body);
    gh_send(client, response);
    gh_close(client);
}

fn self_test() {
    var body: u8[>..] = [];
    assert(route("GET", "/health", body) == 200);
    assert(route("GET", "/nope", body) == 404);
    assert(route("POST", "/", body) == 405);
    print("self-test passed");
}

fn main() {
    var flag: u8[>..] = [];
    if arg_count() > 1 { arg(1, flag); }
    if starts_with(flag, "--self-test") { self_test(); return; }

    let port = port_from_env();
    let server = gh_listen(port);
    guard server >= 0 else { print("cannot listen on port ", port); exit(1); }
    print("[LazyStack] ${c.name} (Goose HTTP) listening on :", port);
    flush_stdout();

    var buf: u8[>..] = [];
    for i in 8192 { buf.push(0); }
    loop {
        let client = gh_accept(server);
        if client >= 0 { handle(client, buf); }
    }
}
`,
    'src/main.build': '// Goose sidecar for main.goose: the C compiled and linked with the program.\nc_sources = ["http.c"];\n',
    'src/http.c': String.raw`/* POSIX TCP plumbing for main.goose. Goose slices cross the extern boundary
   as { data, len } structs, declared here as gh_bytes. Linux and macOS;
   on Windows build in WSL or with the Dockerfile. */
#include <signal.h>
#include <stdint.h>
#include <string.h>
#include <unistd.h>
#include <arpa/inet.h>
#include <netinet/in.h>
#include <sys/socket.h>

typedef struct { uint8_t *data; int64_t len; } gh_bytes;

int32_t gh_listen(int32_t port) {
    signal(SIGPIPE, SIG_IGN);
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) return -1;
    int one = 1;
    setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);
    struct sockaddr_in addr;
    memset(&addr, 0, sizeof addr);
    addr.sin_family = AF_INET;
    addr.sin_addr.s_addr = htonl(INADDR_ANY);
    addr.sin_port = htons((uint16_t)port);
    if (bind(fd, (struct sockaddr *)&addr, sizeof addr) < 0 || listen(fd, 64) < 0) {
        close(fd);
        return -1;
    }
    return fd;
}

int32_t gh_accept(int32_t server) { return accept(server, NULL, NULL); }

int64_t gh_recv(int32_t fd, gh_bytes buf) {
    ssize_t n = recv(fd, buf.data, (size_t)buf.len, 0);
    return n < 0 ? 0 : (int64_t)n;
}

void gh_send(int32_t fd, gh_bytes data) {
    int64_t off = 0;
    while (off < data.len) {
        ssize_t n = send(fd, data.data + off, (size_t)(data.len - off), 0);
        if (n <= 0) break;
        off += n;
    }
}

void gh_close(int32_t fd) { close(fd); }
`,
    '.gitignore': '/build/\n/src/main\n*.o\n.env.local\n',
    'README.md': readme(`${c.name} (Goose HTTP)`, '[Goose](https://aardappel.github.io/goose/) HTTP service generated by LazyStack. Goose has no networking module yet, so the socket layer is a small C file bound with `extern fn`; routing and responses are Goose.', [
      ['Layout', '- `src/main.goose`: routes, request parsing and the accept loop (`PORT`, default ' + port + ')\n- `src/http.c`: POSIX sockets (listen/accept/recv/send)\n- `src/main.build`: Goose sidecar that adds `http.c` to the build'],
      ['Develop', shell('goose build -o build/server src/main.goose   # needs gcc or clang\n./build/server\ncurl localhost:' + port + '/health')],
      ['Test', shell('goose run src/main.goose -- --self-test\ngoose check src/main.goose')],
      ['Add a route', 'Add a branch to `route()` in `src/main.goose`: it gets the method and path, appends the JSON body and returns the status.'],
      ['Install Goose', 'Download a release from https://github.com/aardappel/goose/releases and put it on PATH (macOS: `brew install goose-lang`). Linux needs `libc6-dev` / `glibc-devel` and gcc or clang.']
    ])
  }
}

