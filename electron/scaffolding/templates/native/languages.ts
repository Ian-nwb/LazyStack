function dartShelf(c: NativeContext): Files {
  const port = c.port || 8080
  return {
    'pubspec.yaml': `name: ${c.snake}\ndescription: ${c.name} Shelf service\nversion: 1.0.0\npublish_to: none\n\nenvironment:\n  sdk: ^3.5.0\n\ndependencies:\n  shelf: ^1.4.0\n  shelf_router: ^1.1.0\n\ndev_dependencies:\n  lints: ^5.0.0\n  test: ^1.25.0\n`,
    'analysis_options.yaml': 'include: package:lints/recommended.yaml\n',
    'bin/server.dart': `import 'dart:io';\n\nimport 'package:${c.snake}/app.dart';\nimport 'package:shelf/shelf_io.dart' as shelf_io;\n\nFuture<void> main() async {\n  final port = int.parse(Platform.environment['PORT'] ?? '${port}');\n  final server = await shelf_io.serve(buildHandler(), InternetAddress.anyIPv4, port);\n  print('[LazyStack] ${c.name} (Shelf) listening on :\${server.port}');\n}\n`,
    'lib/app.dart': `import 'dart:convert';\n\nimport 'package:shelf/shelf.dart';\nimport 'package:shelf_router/shelf_router.dart';\n\nResponse _json(Object body) =>\n    Response.ok(jsonEncode(body), headers: {'content-type': 'application/json'});\n\nHandler buildHandler() {\n  final router = Router()\n    ..get('/', (Request request) => _json({'service': '${c.name}', 'framework': 'Shelf', 'status': 'online'}))\n    ..get('/health', (Request request) => _json({'status': 'healthy'}));\n\n  return const Pipeline().addMiddleware(logRequests()).addHandler(router.call);\n}\n`,
    'test/app_test.dart': `import 'dart:convert';\n\nimport 'package:${c.snake}/app.dart';\nimport 'package:shelf/shelf.dart';\nimport 'package:test/test.dart';\n\nvoid main() {\n  test('health reports healthy', () async {\n    final response = await buildHandler()(Request('GET', Uri.parse('http://localhost/health')));\n    expect(response.statusCode, 200);\n    expect(jsonDecode(await response.readAsString()), {'status': 'healthy'});\n  });\n}\n`,
    '.gitignore': '.dart_tool/\n.packages\nbuild/\npubspec.lock\nbin/server\n.env.local\n',
    'README.md': readme(`${c.name} (Dart Shelf)`, 'Plain Dart HTTP service generated by LazyStack using Shelf and shelf_router.', [
      ['Layout', '- `bin/server.dart`: entry point\n- `lib/app.dart`: router and middleware\n- `test/`: `package:test` tests'],
      ['Develop', shell('dart pub get\ndart run bin/server.dart\ndart test')],
      ['Release build', shell('dart compile exe bin/server.dart -o bin/server\n./bin/server')]
    ])
  }
}

function serverpod(c: NativeContext): Files {
  const port = c.port || 8080
  return {
    'setup.sh': `#!/usr/bin/env bash\n# Creates the Serverpod project next to this README. Requires the Dart SDK and Docker.\nset -euo pipefail\n\ndart pub global activate serverpod_cli\nexport PATH="$PATH:$HOME/.pub-cache/bin"\n\nserverpod create ${c.snake}\n`,
    'config/.gitkeep': '',
    '.gitignore': `.dart_tool/\n.packages\nbuild/\npubspec.lock\n${c.snake}/**/config/passwords.yaml\n.env.local\n`,
    'README.md': readme(`${c.name} (Serverpod)`, 'Serverpod is a Dart backend with a generated client. It runs on the host and needs the `serverpod` CLI and Docker for its Postgres and Redis. LazyStack does not add a Compose service for it.', [
      ['Install', shell('dart pub global activate serverpod_cli\nexport PATH="$PATH:$HOME/.pub-cache/bin"   # add to your shell profile')],
      ['Create the project', `Run \`./setup.sh\` or \`serverpod create ${c.snake}\` in this folder. The CLI generates three packages: \`${c.snake}_server\`, \`${c.snake}_client\` and \`${c.snake}_flutter\`.`],
      ['Run', shell(`cd ${c.snake}/${c.snake}_server\ndocker compose up --build --detach   # Postgres + Redis for Serverpod\ndart bin/main.dart --apply-migrations`)],
      ['Ports', `Set the API port in \`${c.snake}/${c.snake}_server/config/development.yaml\` (default 8080). LazyStack expects ${port}.`]
    ])
  }
}

