// --- Static site generators (non-Node) -------------------------------------------------------

function hugo(c: NativeContext): Files {
  const port = c.port || 1313
  return {
    'hugo.toml': `baseURL = "/"\nlanguageCode = "en-us"\ntitle = "${c.name}"\n`,
    'archetypes/default.md': `+++\ntitle = '{{ replace .File.ContentBaseName "-" " " | title }}'\ndate = {{ .Date }}\ndraft = true\n+++\n`,
    'content/_index.md': `+++\ntitle = '${c.name}'\n+++\n\nHugo is serving this site on port ${port}.\n`,
    'content/posts/hello-world.md': `+++\ntitle = 'Hello world'\ndate = 2024-01-01T00:00:00Z\ndraft = false\n+++\n\nYour first post. Create more with \`hugo new content posts/my-post.md\`.\n`,
    'layouts/_default/baseof.html': `<!doctype html>\n<html lang="{{ site.Language.LanguageCode }}">\n  <head>\n    <meta charset="utf-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1" />\n    <title>{{ if .IsHome }}{{ site.Title }}{{ else }}{{ .Title }} | {{ site.Title }}{{ end }}</title>\n    <link rel="stylesheet" href="/css/style.css" />\n  </head>\n  <body>\n    <nav><a href="/">Home</a> <a href="/posts/">Posts</a></nav>\n    <main>{{ block "main" . }}{{ end }}</main>\n  </body>\n</html>\n`,
    'layouts/index.html': `{{ define "main" }}\n  <h1>{{ .Title }}</h1>\n  {{ .Content }}\n{{ end }}\n`,
    'layouts/_default/list.html': `{{ define "main" }}\n  <h1>{{ .Title }}</h1>\n  <ul>\n    {{ range .Pages }}<li><a href="{{ .RelPermalink }}">{{ .Title }}</a></li>{{ end }}\n  </ul>\n{{ end }}\n`,
    'layouts/_default/single.html': `{{ define "main" }}\n  <h1>{{ .Title }}</h1>\n  {{ .Content }}\n{{ end }}\n`,
    'static/css/style.css': `body {\n  font-family: system-ui, sans-serif;\n  margin: 2rem auto;\n  max-width: 40rem;\n}\n\nnav {\n  display: flex;\n  gap: 1rem;\n  margin-bottom: 2rem;\n}\n`,
    'assets/.gitkeep': '',
    'data/.gitkeep': '',
    'i18n/.gitkeep': '',
    '.gitignore': '/public/\n/resources/_gen/\n/assets/jsconfig.json\nhugo_stats.json\n.hugo_build.lock\n.env.local\n',
    'README.md': readme(`${c.name} (Hugo)`, `Hugo site generated by LazyStack (\`hugo new site\` layout, no theme). In Docker the site is built with Hugo, then served by nginx on port ${port}.`, [
      ['Layout', '- `hugo.toml`: site config\n- `content/`: Markdown pages\n- `layouts/`: templates\n- `static/`, `assets/`, `data/`, `i18n/`, `archetypes/`'],
      ['Develop', shell(`hugo server --bind 0.0.0.0 --port ${port}`)],
      ['Build', shell('hugo --minify   # output in public/')],
      ['Install Hugo', 'See https://gohugo.io/installation/ (the extended edition is only needed for Sass).']
    ])
  }
}

