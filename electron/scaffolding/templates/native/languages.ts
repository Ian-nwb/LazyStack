// --- Gleam, V, Dart --------------------------------------------------------------------------

function gleamWisp(c: NativeContext): Files {
  const port = c.port || 8000
  return {
    'gleam.toml': `name = "${c.snake}"\nversion = "1.0.0"\n\n[dependencies]\ngleam_stdlib = ">= 0.40.0 and < 2.0.0"\ngleam_erlang = ">= 0.33.0 and < 1.0.0"\ngleam_http = ">= 3.7.0 and < 4.0.0"\nmist = ">= 4.0.0 and < 5.0.0"\nwisp = ">= 1.5.0 and < 2.0.0"\n\n[dev-dependencies]\ngleeunit = ">= 1.0.0 and < 2.0.0"\n`,
    [`src/${c.snake}.gleam`]: `import ${c.snake}/router\nimport gleam/erlang/process\nimport mist\nimport wisp\nimport wisp/wisp_mist\n\npub fn main() {\n  wisp.configure_logger()\n  let secret_key_base = wisp.random_string(64)\n\n  let assert Ok(_) =\n    wisp_mist.handler(router.handle_request, secret_key_base)\n    |> mist.new\n    |> mist.bind("0.0.0.0")\n    |> mist.port(${port})\n    |> mist.start_http\n\n  process.sleep_forever()\n}\n`,
    [`src/${c.snake}/router.gleam`]: `import wisp.{type Request, type Response}\n\npub fn handle_request(req: Request) -> Response {\n  use <- wisp.log_request(req)\n  use <- wisp.rescue_crashes\n\n  case wisp.path_segments(req) {\n    [] ->\n      wisp.json_response(\n        "{\\"service\\":\\"${c.name}\\",\\"framework\\":\\"Wisp\\",\\"status\\":\\"online\\"}",\n        200,\n      )\n    ["health"] -> wisp.json_response("{\\"status\\":\\"healthy\\"}", 200)\n    _ -> wisp.not_found()\n  }\n}\n`,
    [`test/${c.snake}_test.gleam`]: `import ${c.snake}/router\nimport gleeunit\nimport gleeunit/should\nimport wisp/testing\n\npub fn main() {\n  gleeunit.main()\n}\n\npub fn health_test() {\n  let response = router.handle_request(testing.get("/health", []))\n\n  response.status\n  |> should.equal(200)\n}\n`,
    '.gitignore': '*.beam\n*.ez\n/build\nerl_crash.dump\n.env.local\n',
    'README.md': readme(`${c.name} (Gleam + Wisp)`, 'Gleam web service on the BEAM, generated by LazyStack (`gleam new` layout, Wisp on the Mist server).', [
      ['Layout', `- \`gleam.toml\`: package and dependencies\n- \`src/${c.snake}.gleam\`: entry point (Mist server)\n- \`src/${c.snake}/router.gleam\`: request handling\n- \`test/\`: gleeunit tests`],
      ['Develop', shell('gleam run\ngleam test')],
      ['Release build', shell('gleam export erlang-shipment\nbuild/erlang-shipment/entrypoint.sh run')]
    ])
  }
}

