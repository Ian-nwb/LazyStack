import { ProjectSettings } from '../../../src/types'
import { DATABASE_CATALOG } from '../../../src/data/databases'
import { resolveStructurePaths } from '../../../src/data/structurePresets'
import { getDbServiceName } from './docker'
import crypto from 'crypto'

export function generateMetaFiles(settings: ProjectSettings): Record<string, string> {
  const files: Record<string, string> = {}
  const activeDbs = settings.databases.filter(d => d.enabled)
  const paths = resolveStructurePaths(settings)

  // 1. Root .env and .env.example
  let env = `# Generated by LazyStack for ${settings.projectName}\nPROJECT_NAME=${settings.projectName}\nNODE_ENV=development\nARCHITECTURE_LAYOUT=${settings.structureConfig?.preset || 'monorepo'}\n\n`
  let envExample = `# LazyStack Environment Variables Example\nPROJECT_NAME=${settings.projectName}\nNODE_ENV=development\nARCHITECTURE_LAYOUT=${settings.structureConfig?.preset || 'monorepo'}\n\n`

  settings.apps.forEach(app => {
    const key = `${app.folderName.toUpperCase().replace(/[^A-Z0-9]/g, '_')}_PORT`
    env += `${key}=${app.port}\n`
    envExample += `${key}=${app.port}\n`
  })

  // Only generate local credentials for self-hosted databases
  const selfHostedDbs = activeDbs.filter(d => {
    const def = DATABASE_CATALOG.find(c => c.id === d.type)
    return !def?.isCloud
  })

  selfHostedDbs.forEach((db, idx) => {
    const sName = getDbServiceName(db, idx, settings.apps).toUpperCase()
    const randPass = crypto.randomBytes(8).toString('hex')
    const assignedApp = settings.apps.find(a => a.id === db.assignedAppId)
    const scopeNote = assignedApp ? `[Scoped to ${assignedApp.folderName}]` : '[Global Infrastructure]'

    env += `\n# ${db.customName || sName} Database Credentials ${scopeNote}\n`
    env += `${sName}_PORT=${db.port}\n`
    env += `${sName}_USER=lazystack_user\n`
    env += `${sName}_PASSWORD=${randPass}\n`
    env += `${sName}_DB=${db.databaseName || `lazystack_${db.type}`}\n`

    envExample += `\n# ${db.customName || sName} Database Credentials ${scopeNote}\n`
    envExample += `${sName}_PORT=${db.port}\n`
    envExample += `${sName}_USER=lazystack_user\n`
    envExample += `${sName}_PASSWORD=change_this_secret_password\n`
    envExample += `${sName}_DB=${db.databaseName || `lazystack_${db.type}`}\n`
  })

  files['.env'] = env
  files['.env.example'] = envExample

  // 2. .gitignore
  files['.gitignore'] = `# Generated by LazyStack
.env
node_modules/
dist/
build/
*.log
*.tmp

# Database volume data
infra/sqlite/*.db
infra/sqlite/*.db-shm
infra/sqlite/*.db-wal
postgres_data/
mysql_data/
mariadb_data/
redis_data/
mongo_data/

# IDE files
.idea/
*.suo
*.ntvs*
*.njsproj
*.sln.docstates
`

  // 3. .gitattributes (enforce LF for dev.sh)
  files['.gitattributes'] = `* text=auto eol=lf\nscripts/*.sh text eol=lf\n`

  // 4. scripts/dev.sh (POSIX)
  files['scripts/dev.sh'] = `#!/usr/bin/env bash
# LazyStack One-Command Development Launcher (POSIX)
set -e

DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"
cd "$DIR"

echo "=========================================="
echo " Starting LazyStack: ${settings.projectName}"
echo "=========================================="

if ! command -v docker &> /dev/null; then
    echo "ERROR: Docker is required but not installed." >&2
    exit 1
fi

echo "[*] Launching containerized services..."
docker compose --env-file .env -f infra/docker-compose.yml -f infra/docker-compose.dev.yml up -d --build

echo ""
echo "✅ All services started successfully!"
echo "📍 Reverse Proxy Gateway: http://localhost:${settings.proxy.httpPort}"
echo "📊 Run 'docker compose -f infra/docker-compose.yml logs -f' to stream logs."
`

  // 5. scripts/dev.ps1 (PowerShell)
  files['scripts/dev.ps1'] = `# LazyStack One-Command Development Launcher (Windows PowerShell)
$ErrorActionPreference = "Stop"
$ProjectDir = Split-Path -Parent $PSScriptRoot
Set-Location $ProjectDir

Write-Host "==========================================" -ForegroundColor Cyan
Write-Host " Starting LazyStack: ${settings.projectName}" -ForegroundColor Cyan
Write-Host "==========================================" -ForegroundColor Cyan

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Error "ERROR: Docker is required but not installed on this system."
    exit 1
}

Write-Host "[*] Launching containerized services..." -ForegroundColor Yellow
docker compose --env-file .env -f infra/docker-compose.yml -f infra/docker-compose.dev.yml up -d --build

Write-Host ""
Write-Host "All services started successfully!" -ForegroundColor Green
Write-Host "Reverse Proxy Gateway: http://localhost:${settings.proxy.httpPort}" -ForegroundColor Green
`

  // 6. tests/healthcheck.sh
  files['tests/healthcheck.sh'] = `#!/usr/bin/env bash
set -e
echo "Running health checks for ${settings.projectName}..."

${settings.apps.filter(a => a.port > 0).map(a => `echo "Testing ${a.folderName} on port ${a.port}..."
curl -s -f "http://localhost:${a.port}/" || echo "Warning: ${a.folderName} did not respond"
`).join('\n')}
echo "All automated healthchecks completed."
`

  // 7. Root package.json (Monorepo Workspaces)
  files['package.json'] = JSON.stringify({
    name: settings.projectName.toLowerCase().replace(/[^a-z0-9_-]/g, '-'),
    version: '1.0.0',
    private: true,
    description: `Monorepo stack generated with LazyStack`,
    workspaces: [
      `${paths.appsDir}/*`,
      `${paths.packagesDir}/*`
    ],
    scripts: {
      dev: `./${paths.scriptsDir}/dev.sh`,
      'dev:ps1': `powershell -ExecutionPolicy Bypass -File ./${paths.scriptsDir}/dev.ps1`,
      'docker:up': `docker compose --env-file .env -f ${paths.infraDir}/docker-compose.yml up -d`,
      'docker:down': `docker compose --env-file .env -f ${paths.infraDir}/docker-compose.yml down`,
      'docker:logs': `docker compose -f ${paths.infraDir}/docker-compose.yml logs -f`,
      'health': './tests/healthcheck.sh'
    }
  }, null, 2) + '\n'

  // 8. pnpm-workspace.yaml
  files['pnpm-workspace.yaml'] = `packages:\n  - '${paths.appsDir}/*'\n  - '${paths.packagesDir}/*'\n`

  // Shared Monorepo Packages
  const safeScope = settings.projectName.toLowerCase().replace(/[^a-z0-9_-]/g, '-')
  files[`${paths.packagesDir}/types/package.json`] = JSON.stringify({
    name: `@${safeScope}/types`,
    version: '1.0.0',
    private: true,
    main: './index.ts',
    types: './index.ts'
  }, null, 2) + '\n'

  files[`${paths.packagesDir}/types/index.ts`] = `// Shared TypeScript interfaces across all monorepo apps
export interface ApiResponse<T = any> {
  success: boolean
  data?: T
  error?: string
  timestamp: string
}

export interface UserSession {
  userId: string
  role: 'admin' | 'user' | 'guest'
}
`

  files[`${paths.packagesDir}/shared/package.json`] = JSON.stringify({
    name: `@${safeScope}/shared`,
    version: '1.0.0',
    private: true,
    main: './src/index.ts'
  }, null, 2) + '\n'

  files[`${paths.packagesDir}/shared/src/index.ts`] = `// Shared utility functions across all monorepo apps
export const formatTimestamp = (date: Date = new Date()): string => {
  return date.toISOString()
}

export const delay = (ms: number): Promise<void> => {
  return new Promise(resolve => setTimeout(resolve, ms))
}
`

  // 9. turbo.json (Monorepo Pipeline)
  files['turbo.json'] = JSON.stringify({
    $schema: 'https://turbo.build/schema.json',
    tasks: {
      build: {
        dependsOn: ['^build'],
        outputs: ['.next/**', '!.next/cache/**', 'dist/**', 'build/**', 'target/**']
      },
      dev: {
        cache: false,
        persistent: true
      },
      test: {
        dependsOn: ['build']
      }
    }
  }, null, 2) + '\n'

  // 10. .vscode/settings.json
  files['.vscode/settings.json'] = JSON.stringify({
    'editor.formatOnSave': true,
    'files.autoSave': 'onFocusChange',
    'docker.compose.showComposeFile': true,
    'explorer.autoReveal': true
  }, null, 2) + '\n'

  // 11. .vscode/launch.json
  files['.vscode/launch.json'] = JSON.stringify({
    version: '0.2.0',
    configurations: settings.apps.filter(a => a.port > 0).map(a => ({
      name: `Debug: ${a.folderName} (${a.techId})`,
      type: 'node',
      request: 'launch',
      cwd: `\${workspaceFolder}/apps/${a.folderName}`,
      runtimeExecutable: 'npm',
      runtimeArgs: ['run', 'dev'],
      port: a.port
    }))
  }, null, 2) + '\n'

  // 12. .vscode/extensions.json
  files['.vscode/extensions.json'] = JSON.stringify({
    recommendations: [
      "ms-azuretools.vscode-docker",
      "redhat.vscode-yaml",
      "dotenv.dotenv-vscode",
      "editorconfig.editorconfig"
    ]
  }, null, 2) + '\n'

  // 8. .github/workflows/ci.yml
  files['.github/workflows/ci.yml'] = `name: CI

on:
  push:
    branches: [ main, master ]
  pull_request:
    branches: [ main, master ]

jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Validate Docker Compose Configuration
        run: docker compose -f infra/docker-compose.yml config
`

  // 9. README.md
  files['README.md'] = `# ${settings.projectName}

Modular monorepo architecture scaffolded with **LazyStack**.

---

## 🏗 Project Architecture

This project follows the enforced LazyStack directory contract:

\`\`\`text
${settings.projectName}/
├── .github/workflows/     # Automated CI/CD
├── .vscode/               # Workspace editor settings
├── apps/                  # Application microservices
${settings.apps.map(a => `│   └── ${a.folderName}/       # ${a.techId} (Port: ${a.port}, RunMode: ${a.runMode})`).join('\n')}
├── docs/                  # Architecture & API documentation
├── infra/                 # Docker Compose & Proxy
│   ├── docker-compose.yml # Production orchestration
│   └── docker-compose.dev.yml # Dev override
├── scripts/               # dev.sh and dev.ps1 launchers
├── tests/                 # Integration test suite
├── .env                   # Environment secrets (git-ignored)
├── .env.example           # Example environment template
└── README.md
\`\`\`

---

## 🚀 Quick Start

### 1. Start All Services
On Linux/macOS:
\`\`\`bash
chmod +x scripts/dev.sh
./scripts/dev.sh
\`\`\`

On Windows (PowerShell):
\`\`\`powershell
.\\scripts\\dev.ps1
\`\`\`

---

## 🌐 Application Services & Ports

| Service | Technology | Port | Run Mode | Proxy Route |
| :--- | :--- | :--- | :--- | :--- |
${activeDbs.map(d => {
  const def = DATABASE_CATALOG.find(c => c.id === d.type)
  if (def?.isCloud && d.type !== 'pocketbase') {
    return `| \`${def?.name || d.type}\` | Cloud / BaaS | Managed | Cloud API | External |`
  }
  return `| \`${d.type}\` | Database | \`${d.port}\` | Docker Container | Internal |`
}).join('\n')}

---

*Generated by LazyStack Studio.*
`

  return files
}
