    files[`${paths.packagesDir}/events/src/consumer.ts`] = `// Typed Event Consumer Worker Harness with Retry & Dead-Letter Queue
import { BaseEvent, RetryPolicy, DEFAULT_RETRY_POLICY } from './index.js'

export type EventHandler<T = any> = (event: BaseEvent<T>) => Promise<void>

export class EventConsumerWorker {
  constructor(
    private policy: RetryPolicy = DEFAULT_RETRY_POLICY,
    private onDlq?: (dlqEvent: BaseEvent) => Promise<void>
  ) {}

  async processEvent<T>(event: BaseEvent<T>, handler: EventHandler<T>): Promise<void> {
    let attempt = 0
    while (attempt <= this.policy.maxRetries) {
      try {
        await handler(event)
        return
      } catch (err: any) {
        attempt++
        event.retryCount = attempt
        if (attempt > this.policy.maxRetries) {
          console.error(\`[EventConsumerWorker] Max retries (\${this.policy.maxRetries}) exceeded for event \${event.id} on \${event.topic}. Routing to DLQ: \${this.policy.dlqTopic}\`)
          if (this.onDlq) {
            await this.onDlq({
              id: \`dlq_\${Date.now()}_\${Math.random().toString(36).slice(2, 7)}\`,
              topic: this.policy.dlqTopic,
              source: 'worker.dlq_pipeline',
              data: {
                failedEvent: event,
                error: err?.message || String(err),
                failedAt: new Date().toISOString(),
                attempts: attempt
              },
              timestamp: new Date().toISOString()
            })
          }
          return
        }
        const delay = Math.min(this.policy.backoffMs * Math.pow(2, attempt - 1), this.policy.maxBackoffMs || 10000)
        console.warn(\`[EventConsumerWorker] Handler failed for \${event.id} (attempt \${attempt}/\${this.policy.maxRetries}). Retrying in \${delay}ms...\`)
        await new Promise(r => setTimeout(r, delay))
      }
    }
  }
}
`

