/**
 * Generates environment variable entries for cloud services.
 * Returns lines to append to .env and .env.example files.
 */
export function generateCloudEnvVars(databases: SelectedDatabase[]): { env: string; envExample: string } {
  const activeCloud = databases.filter(d => {
    if (!d.enabled) return false
    const def = DATABASE_CATALOG.find(c => c.id === d.type)
    return def?.isCloud
  })

  if (activeCloud.length === 0) return { env: '', envExample: '' }

  let env = '\n# ─── Cloud & BaaS Services (LazyStack) ───────────────────────\n'
  let envExample = '\n# ─── Cloud & BaaS Services (LazyStack) ───────────────────────\n'

  for (const db of activeCloud) {
    const def = DATABASE_CATALOG.find(c => c.id === db.type)
    if (!def?.envVars) continue

    env += `\n# ${def.name}\n`
    envExample += `\n# ${def.name}\n`

    for (const envVar of def.envVars) {
      env += `${envVar}=\n`
      envExample += `${envVar}=your_${envVar.toLowerCase()}_here\n`

      // Also generate NEXT_PUBLIC_ variants for frontend-accessible vars
      if (['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN',
           'FIREBASE_PROJECT_ID', 'FIREBASE_STORAGE_BUCKET', 'APPWRITE_ENDPOINT',
           'APPWRITE_PROJECT_ID', 'CONVEX_URL'].includes(envVar)) {
        env += `NEXT_PUBLIC_${envVar}=\n`
        envExample += `NEXT_PUBLIC_${envVar}=your_${envVar.toLowerCase()}_here\n`
      }
    }
  }

  return { env, envExample }
}

/**
 * Returns the list of npm packages to install for cloud services,
 * categorized by ecosystem.
 */
export function getCloudSdkInstallCommands(databases: SelectedDatabase[]): string[] {
  const commands: string[] = []
  const npmPackages: string[] = []
  const pipPackages: string[] = []

  const activeCloud = databases.filter(d => {
    if (!d.enabled) return false
    const def = DATABASE_CATALOG.find(c => c.id === d.type)
    return def?.isCloud
  })

  for (const db of activeCloud) {
    const def = DATABASE_CATALOG.find(c => c.id === db.type)
    if (!def?.sdkPackages) continue

    if (def.sdkPackages.npm) {
      npmPackages.push(...def.sdkPackages.npm.split(' '))
    }
    if (def.sdkPackages.pip) {
      pipPackages.push(...def.sdkPackages.pip.split(' '))
    }
  }

  if (npmPackages.length > 0) {
    commands.push(`npm install ${npmPackages.join(' ')}`)
  }
  if (pipPackages.length > 0) {
    commands.push(`pip install ${pipPackages.join(' ')}`)
  }

  return commands
}
